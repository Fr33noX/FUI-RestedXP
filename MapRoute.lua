-- Yards per normalized step on each axis of a map, measured rather than
-- assumed: a zone is rarely square (a wide Barrens, a tall Tirisfal), so
-- one scale applied to both axes bends the bearing. The client's own world
-- size answers when it exposes one; otherwise two positions of the map
-- itself are read and the distance between them taken -- a MAGNITUDE, so
-- the orientation of the client's world frame (whatever it happens to be
-- on this build) cannot leak into the answer. Cached: a map never changes
-- size, and this runs ten times a second.
local yardScale = {}
local function MapYardScale(mapID)
    if type(mapID) ~= "number" or IsSecret(mapID) then return nil end
    local c = yardScale[mapID]
    if c then return c[1], c[2] end
    local w, h
    if C_Map and type(C_Map.GetMapWorldSize) == "function" then
        local ok, ww, hh = pcall(C_Map.GetMapWorldSize, mapID)
        if ok and type(ww) == "number" and type(hh) == "number"
            and ww == ww and hh == hh and ww > 0 and hh > 0 then
            w, h = ww, hh
        end
    end
    if not (w and h) then
        -- 0/0 and 0.5/0.5, not 0/1: the far corner is translated a little
        -- inaccurately on some maps, and HereBeDragons measures the same
        -- way for the same reason.
        local x0, y0 = MapWorldPos(mapID, 0, 0)
        local x1, y1 = MapWorldPos(mapID, 0.5, 0)
        local x2, y2 = MapWorldPos(mapID, 0, 0.5)
        if x0 and x1 and x2 and y0 and y1 and y2 then
            local dx, dy = x1 - x0, y1 - y0
            w = 2 * math.sqrt(dx * dx + dy * dy)
            dx, dy = x2 - x0, y2 - y0
            h = 2 * math.sqrt(dx * dx + dy * dy)
        end
    end
    if not (w and h and w == w and h == h and w > 0 and h > 0
        and w < 1000000 and h < 1000000) then
        return nil
    end
    yardScale[mapID] = { w, h }
    return w, h
end

-- Forever quirks worth defending against:
-- C_Map.GetBestMapForUnit() can answer nil through deaths, ghost runs and
-- some map transitions even though a position CAN be read once a map is
-- named for it. So: a short list of candidates (Blizzard's own lookup,
-- then MapUtil's displayable map, then the last map that worked), each
-- accepted only when it really answers with a position -- and, as a last
-- resort, the last anchor held for five seconds. On the minimap the player
-- is the CENTRE by construction, so a stale anchor costs bearing accuracy
-- only, never where the line starts; five seconds bridges a transition and
-- is short enough to stay honest. `cached` rides along for the diagnostic.
local anchor = { map = nil, x = nil, y = nil, at = 0 }
PlayerAnchor = function()
    local now = (type(GetTime) == "function") and GetTime() or 0
    local cand, n = {}, 0
    local function push(id)
        if type(id) ~= "number" or IsSecret(id) or id <= 0 then return end
        for i = 1, n do if cand[i] == id then return end end
        n = n + 1
        cand[n] = id
    end
    if C_Map and type(C_Map.GetBestMapForUnit) == "function" then
        local ok, id = pcall(C_Map.GetBestMapForUnit, "player")
        if ok then push(id) end
    end
    if MapUtil and type(MapUtil.GetDisplayableMapForPlayer) == "function" then
        local ok, id = pcall(MapUtil.GetDisplayableMapForPlayer)
        if ok then push(id) end
    end
    push(anchor.map)
    for i = 1, n do
        -- pcall'd: a candidate comes from a fallback and an odd map id must
        -- cost one line of status, not an error frame ten times a second.
        local okP, x, y = pcall(PlayerSpot, cand[i])
        if okP and x and y then
            anchor.map, anchor.x, anchor.y, anchor.at = cand[i], x, y, now
            return cand[i], x, y, false
        end
    end
    if anchor.map and anchor.at > 0 and (now - anchor.at) <= 5 then
        return anchor.map, anchor.x, anchor.y, true
    end
    return cand[1], nil, nil, false
end

-- One pass over the glass. Everything is measured from the player, who
-- sits at its centre, on the player's OWN map: the target is brought to
-- that map by the same reprojection the world map uses, and the direction
-- is read from THAT map's coordinates -- x east, y south, north at the
-- top -- which is the convention the world map route and the tooltip's
-- compass are already drawn from. No client
-- world axis is ever assumed here: the first version took its vector from
-- C_Map's world position and pointed the line somewhere else entirely.
-- ---------------- The overlay layer on the minimap ----------------
-- Farm circuits and patrols only: a search area's fill at this size would
-- be a smudge smaller than your hand. The same colors, the same dash, the
-- same one opacity -- projected through the very numbers the route above
-- them uses (yard scales, rotation, rim), clamped inside the glass so a
-- shape crossing the edge bends at the rim instead of running off it.
local ovMLine, ovMLineN, ovMLineMax = {}, 0, 0
-- Squared yards from the player to the nearest point any shape of this pass
-- projected. A shape lying wholly beyond the view radius is left off the
-- glass ON PURPOSE -- a point projection answers nil past the radius, and
-- that is what keeps it honest -- so "no stroke here" and
-- "nothing within reach" read identically in a chat line. This is what
-- tells the two apart.
local ovNearSq = math.huge

MiniOverlayRelease = function()
    for i = 1, ovMLineMax do if ovMLine[i] then ovMLine[i]:Hide() end end
    ovMLineN, ovMLineMax = 0, 0
    M.overlayMiniDrawn = nil
    M.overlayMiniNear = nil
end

