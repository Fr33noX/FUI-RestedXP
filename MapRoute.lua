-- ---------------- Hovering a marker ----------------
-- What the tooltip shows, in order: which marker this is and the step it
-- belongs to, that step's own title, WHAT THE STEP ASKS FOR (its own text
-- lines -- the marker's element has none of them), what the marker points
-- at (the named NPC or item, the kind of step), how far and
-- which way it lies with a rough arrival time, then the quest behind it --
-- title, level in the log's own difficulty colour, where that quest stands
-- in the log, its objectives and its id -- the instance when the marker
-- sits in one, and the zone. Every line is optional and guarded: this
-- client has answered with nil often enough that a missing API must cost a
-- line of tooltip, never an error frame, and a line whose data is simply
-- absent stays away rather than printing a guess.
local function MapName(id)
    if not (id and C_Map and C_Map.GetMapInfo) then return nil end
    local ok, info = pcall(C_Map.GetMapInfo, id)
    if ok and type(info) == "table" and type(info.name) == "string" then return info.name end
    return nil
end

-- RestedXP tints its guide text with tokens of its own -- the text holds
-- "|cRXP_ENEMY_Vile Familiar|r" where a normal string would hold eight
-- hexadecimal digits. Its font strings swap the token for the theme's
-- colour before drawing; a tooltip that printed it raw would show the
-- token itself. So we swap it the same way, asking RestedXP's own table,
-- which its theme page rewrites whenever the player changes a colour.
local function TokenColor(tok)
    local RXP = ns.GetRXP()
    local t = RXP and RXP.guideTextColors
    if type(t) ~= "table" then return nil end
    local c = t[tok]
    if type(c) ~= "string" and type(t.default) == "table" then c = t.default[tok] end
    if type(c) == "string" and c:match("^%x%x%x%x%x%x%x%x$") then return c end
    return nil
end

-- One line of guide text: newlines flattened (a tooltip line has no room
-- for them) and RestedXP's colour tokens resolved as above -- with the
-- whole escape dropped when its colour table is out of reach, which keeps
-- the words and loses only the tint.
local function OneLine(s)
    if type(s) ~= "string" or s == "" or IsSecret(s) then return nil end
    s = s:gsub("[\r\n]+", " ")
    s = s:gsub("|cRXP_[A-Z]+_", function(tok)
        local hex = TokenColor(tok:sub(3))
        if hex then return "|c" .. hex end
        return ""
    end)
    -- A token left outside an escape means nothing to a tooltip.
    s = s:gsub("RXP_[A-Z]+_", "")
    -- Blank-only counts as absent: a guide line of spaces would print as
    -- an empty row of the tooltip and read as a rendering fault.
    if not s:match("%S") then return nil end
    return s
end

-- Everything this step asks the player to do, in guide order: the marker's
-- own text first, then the step's other text lines. RestedXP writes each
-- instruction as the text of its own element -- "Kill |cRXP_ENEMY_Lizards|r"
-- is a text element -- while the marker follows the step's POSITION
-- element, which carries no such text: reading only the marker said where
-- to go and never what to do there. Capped at four, because a step is a
-- short list of things to do and a tooltip that lists the guide is no
-- longer a tooltip.
local function Instructions(e, stepObj)
    local out, seen = {}, {}
    local function push(el)
        if type(el) ~= "table" or el.skip then return end
        local s = OneLine(el.text) or OneLine(el.rawtext)
        if s and not seen[s] then
            seen[s] = true
            out[#out + 1] = s
        end
    end
    push(e)
    if type(stepObj) == "table" and type(stepObj.elements) == "table" then
        for i = 1, #stepObj.elements do
            if #out >= 4 then break end
            push(stepObj.elements[i])
        end
    end
    return out
end

-- The waypoint label: the step's own headline, same rule as the map
-- tooltip -- element title, step arrow text / title, else the first
-- instruction line. The bare step number is the last resort, so the
-- waypoint reads what the guide is about, not where it sits in it.
local function SpotLabel(e, step)
    local head = (type(e) == "table") and OneLine(e.title) or nil
    if not head and type(step) == "table" then
        head = OneLine(step.arrowtext) or OneLine(step.title)
    end
    if not head then
        local all = Instructions(e, step)
        head = all and all[1]
    end
    if type(head) ~= "string" or head == "" then
        local at = ActiveIndex()
        return (at and ("RestedXP Step " .. at) or "RestedXP")
    end
    return head
end

-- Waypoint bridge: the same target the route draws, for WaypointUI's
-- waypoint instead of our arrow. Normalized 0..1 coordinates, the label
-- above, and WHICH answer it was (arrow element vs current step -- the
-- diagnostic needs it: a stale arrow element points at the previous step).
-- Nil while RestedXP publishes nothing to head for.
function ns.MapRouteSpot()
    -- While the player is a ghost the body outranks the guide, exactly as
    -- in RefreshMap: RestedXP publishes no target from beyond the veil
    -- (its arrow goes quiet), so a reader of this answer alone used to
    -- get nil and take the waypoint down -- WaypointUI showed nothing
    -- while dead. CorpseSpot costs one boolean for a living player.
    local corpseMap, corpseX, corpseY = CorpseSpot()
    if corpseMap then
        return corpseMap, corpseX, corpseY,
            SpotLabel(CorpseElement(), nil), "corpse"
    end
    local af = _G.RXPG_ARROW
    if af then
        local id, x, y = SpotArrow(af.element)
        if id then
            local step = (type(af.element) == "table") and af.element.step or nil
            if type(step) ~= "table" or not step.elements then step = CurrentStep() end
            return id, x, y, SpotLabel(af.element, step), "arrow element"
        end
    end
    local step = CurrentStep()
    local id2, x2, y2, e = SpotInStep(step)
    if id2 then return id2, x2, y2, SpotLabel(e, step), "current step" end
    return nil
end

