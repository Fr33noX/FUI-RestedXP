-- RestedXP stores map coordinates either normalized (0..1) or as 0..100 on
-- some step types, and ingamewaypoint elements under zx/zy instead of x/y.
-- Anything that is not a plain number we can trust is rejected rather than
-- guessed: a wrong coordinate draws a line to the wrong place.
local function Coord(v)
    if type(v) ~= "number" or IsSecret(v) then return nil end
    if v > 1 then v = v / 100 end
    if v < 0 or v > 1 then return nil end
    return v
end

local function MapID(e)
    if type(e) ~= "table" then return nil end
    local id = tonumber(e.zone or e.mapID or e.map)
    if type(id) ~= "number" or IsSecret(id) then return nil end
    return id
end

-- The map position an RXP element resolves to, or nil when it has none.
local function Spot(e)
    if type(e) ~= "table" or e.skip or e.completed then return nil end
    local id = MapID(e)
    if not id then return nil end
    local x, y = e.x, e.y
    if type(x) ~= "number" or type(y) ~= "number" then x, y = e.zx, e.zy end
    x, y = Coord(x), Coord(y)
    if not (x and y) then return nil end
    return id, x, y
end

-- The same, WITHOUT the skip/completed filter, for the arrow's own element
-- only. That frame publishes where RestedXP is actually sending you, and it
-- is routinely seen carrying completed=true while its coordinates are the
-- freshest ones we have -- dropping it on that flag is what sent us hunting
-- through the step while the arrow was holding the answer. Stale flags during
-- a step transition are RestedXP's business, not ours.
local function SpotArrow(e)
    if type(e) ~= "table" then return nil end
    local id = MapID(e)
    if not id then return nil end
    local x, y = e.x, e.y
    if type(x) ~= "number" or type(y) ~= "number" then x, y = e.zx, e.zy end
    x, y = Coord(x), Coord(y)
    if not (x and y) then return nil end
    return id, x, y
end

-- RestedXP's arrow points at whatever the step is about -- a mob, an item,
-- a conversation -- and most of those have no fixed place on the map. So
-- when the element itself carries no coordinates, we look through the
-- current step's own elements for one that does, the way RestedXP places
-- its quest markers. The step comes off the element when it carries one,
-- and otherwise from the guide's progress.
-- Which element of a step RestedXP would actually send you to. The order
-- is RestedXP's, not ours: it flags the elements that carry a real
-- navigation target with arrow=true, ranks the optional ones lowPrio, and
-- marks the rest textOnly. Taking simply the first element that has
-- coordinates picks a line of prose far more often than the objective,
-- which is exactly how the chain ended up somewhere the guide never was.
local function PickStepElement(step)
    if type(step) ~= "table" then return nil end
    if type(step.elements) ~= "table" then return nil end
    local ok = {}
    for _, e in ipairs(step.elements) do
        if type(e) == "table" and not e.skip and not e.completed then ok[#ok + 1] = e end
    end
    local function pick(test)
        for _, e in ipairs(ok) do if test(e) then return e end end
    end
    -- One ranking, to its last line: an arrow that is not
    -- optional, then any arrow, then anything that is not prose -- and
    -- then, where all three come up empty, THE FIRST ELEMENT WITH A PLACE.
    -- That last rule is not a nicety here: RestedXP clears the arrow flag
    -- again on every ".goto zone,x,y,0" it parses (functions.lua:1967), so
    -- on the Forever guides a step of nothing but gotos -- every #loop of a
    -- farming guide -- matched NONE of the three, and the chain of upcoming
    -- steps came back empty: no rings on the glass at all, with the setting
    -- reading six.
    return pick(function(e) return e.arrow == true and not e.lowPrio end)
        or pick(function(e) return e.arrow == true end)
        or pick(function(e) return not e.textOnly end)
        or pick(function(e) return Spot(e) ~= nil end)
end

local function SpotInStep(step)
    local e = PickStepElement(step)
    local id, x, y = Spot(e)
    -- The element rides along: the hover tooltip shows the instruction and
    -- the quest that element carries, and the caller keeps it with the spot.
    return id, x, y, e
end

-- Index of the step RestedXP is on. It marks that step active, and that
-- mark holds better than the progress number, which can still name the
-- previous step while a transition settles.
local function ActiveIndex()
    local RXP = ns.GetRXP()
    local guide = RXP and RXP.currentGuide
    if not (guide and guide.steps) then return nil end
    for i = 1, #guide.steps do
        local s = guide.steps[i]
        if type(s) == "table" and s.active == true and not s.completed then return i end
    end
    local at = (RXP.GetGuideProgress and RXP.GetGuideProgress()) or nil
    return (type(at) == "number" and at >= 1 and at) or nil
end

local function CurrentStep()
    local af = _G.RXPG_ARROW
    local step = af and af.element and af.element.step
    if type(step) == "table" and step.elements then return step end
    local RXP = ns.GetRXP()
    local at = ActiveIndex()
    if at and RXP and RXP.currentGuide and RXP.currentGuide.steps then
        return RXP.currentGuide.steps[at]
    end
    return nil
end

-- RestedXP's current navigation target. Its arrow frame is the only place
-- that publishes the element the guide is actually heading for -- the same
-- frame the reskin engine reads, so nothing new is asked of RestedXP.
-- Returns the map id, the coordinates, and WHICH of the two answers it was
-- (the diagnostic reports it, because the first often has nothing usable).
local function CurrentSpot()
    local af = _G.RXPG_ARROW
    if not af then return nil end
    local id, x, y = SpotArrow(af.element)
    if id then return id, x, y, "arrow element" end
    -- All three, not just the first: taking one here would leave x holding
    -- the label below instead of a coordinate.
    local id2, x2, y2 = SpotInStep(CurrentStep())
    if id2 then return id2, x2, y2, "current step" end
    return nil
end

-- Waypoint bridge: the same target the route draws, for WaypointUI's
-- waypoint instead of our arrow. Normalized 0..1 coordinates, plus a
-- short label. Nil while RestedXP publishes nothing to head for.
-- ---------------- The corpse run ----------------
-- While the player is a ghost RestedXP publishes no target: its arrow
-- goes quiet, and the route that matters is the one back to the body.
-- Blizzard answers where the body lies per map, and the map hierarchy is
-- walked here because a body released to a graveyard in a sub-zone is
-- usually exposed on the PARENT zone map, not on the map the ghost is
-- standing in. Coordinates outside the queried map are rejected: the call
-- answers with projected coordinates for parent/adjacent maps, and a
-- corpse pinned off the parchment is worse than no corpse at all.
local lastPlayerMap, lastCorpseMap, lastCorpseX, lastCorpseY

local function IsCorpseRun()
    if type(UnitIsGhost) == "function" then
        local ok, v = pcall(UnitIsGhost, "player")
        if ok and v then return true end
    end
    if type(UnitIsDeadOrGhost) == "function" then
        local ok, v = pcall(UnitIsDeadOrGhost, "player")
        if ok and v then return true end
    end
    return false
end

-- The map the ghost stands on: GetBestMapForUnit can answer nil in the
-- death -> ghost transition, so the last map it DID answer with is kept
-- and stands in when the client goes quiet.
local function GhostMapID()
    if C_Map and type(C_Map.GetBestMapForUnit) == "function" then
        local ok, id = pcall(C_Map.GetBestMapForUnit, "player")
        if ok and type(id) == "number" and not IsSecret(id) and id > 0 then
            lastPlayerMap = id
            return id
        end
    end
    return lastPlayerMap
end

-- The body's map id and coordinates, or nil. Alive, this answers nil
-- without touching the client at all -- the check is the first thing it
-- does, so a living player pays one boolean for it.
local function CorpseSpot()
    if not IsCorpseRun() then return nil end
    if not (C_DeathInfo and type(C_DeathInfo.GetCorpseMapPosition) == "function") then
        return nil
    end
    local cand, n, seen = {}, 0, {}
    local function add(id)
        if type(id) == "number" and not IsSecret(id) and id > 0 and not seen[id] then
            seen[id] = true
            n = n + 1
            cand[n] = id
        end
    end
    local here = GhostMapID()
    add(here)
    local mapID = here
    for _ = 1, 6 do
        if not (mapID and C_Map and type(C_Map.GetMapInfo) == "function") then break end
        local ok, info = pcall(C_Map.GetMapInfo, mapID)
        if not (ok and type(info) == "table") then break end
        local parent = tonumber(info.parentMapID)
        if not parent or parent == 0 or parent == mapID then break end
        add(parent)
        mapID = parent
    end
    add(lastPlayerMap)
    add(lastCorpseMap)
    for i = 1, n do
        local ok, a, b = pcall(C_DeathInfo.GetCorpseMapPosition, cand[i])
        if ok and a ~= nil then
            local x, y
            local ta = type(a)
            if ta == "number" then
                x, y = a, b
            elseif ta == "table" or ta == "userdata" then
                if type(a.GetXY) == "function" then
                    local okXY, ux, uy = pcall(a.GetXY, a)
                    if okXY then x, y = ux, uy end
                else
                    x, y = a.x, a.y
                end
            end
            if type(x) == "number" and type(y) == "number"
                and not IsSecret(x) and not IsSecret(y)
                and x >= 0 and x <= 1 and y >= 0 and y <= 1
                and (x ~= 0 or y ~= 0) then
                lastCorpseMap, lastCorpseX, lastCorpseY = cand[i], x, y
                return cand[i], x, y
            end
        end
    end
    -- The body was found once and the client stopped repeating itself:
    -- the cached answer is still the body's place, and it never goes
    -- stale while the player has not yet walked back to it.
    if lastCorpseMap and lastCorpseX then
        return lastCorpseMap, lastCorpseX, lastCorpseY
    end
    return nil
end

