-- One element's coordinates into minimap pixels: map steps and yard scales
-- as the bearing above, rotation as the chain above, the rim clamp as both.
-- `inside` rides along for the span rule -- a link is drawn only when at
-- least one end is on the glass.
-- One point ALREADY projected onto the player's own map, into minimap
-- pixels: yard scales and rotation as the chain above, the rim clamp as
-- both. `inside` rides along for the span rule. Shared by the segments
-- projection below and the goto-circuit branch, so the two can never
-- drift apart in arithmetic.
local function MiniOverlayPut(rx, ry, n, px, py, W, H, cs, sn, halfW, halfH, radius, edge)
    local e2 = (rx - px) * W
    local n2 = (py - ry) * H
    local d2 = e2 * e2 + n2 * n2
    if d2 < ovNearSq then ovNearSq = d2 end
    local vx = e2 * cs + n2 * sn
    local vy = n2 * cs - e2 * sn
    local ux, uy
    if radius then
        ux, uy = vx / radius * halfW, vy / radius * halfH
    else
        local l = math.sqrt(vx * vx + vy * vy)
        if l > 0 then ux, uy = vx / l * edge, vy / l * edge else ux, uy = 0, 0 end
    end
    local d = math.sqrt(ux * ux + uy * uy)
    local inside = d <= edge
    if not inside and d > 0 then ux, uy = ux / d * edge, uy / d * edge end
    local p = ovPts[n + 1] or {}
    p.x, p.y, p.inside = ux, uy, inside
    ovPts[n + 1] = p
    return n + 1
end

local function MiniOverlayProject(el, pmap, px, py, W, H, cs, sn, halfW, halfH, radius, edge)
    local zone = tonumber(el.zone)
    if not zone or IsSecret(zone) then return 0 end
    local n = 0
    for i = 1, #el.segments, 2 do
        local sx, sy = tonumber(el.segments[i]), tonumber(el.segments[i + 1])
        local x, y = sx and sx / 100, sy and sy / 100
        if x and y and x >= 0 and x <= 1 and y >= 0 and y <= 1
            and not IsSecret(x) and not IsSecret(y) then
            local rx, ry = ReProject(zone, x, y, pmap)
            if rx and ry then
                n = MiniOverlayPut(rx, ry, n, px, py, W, H, cs, sn,
                    halfW, halfH, radius, edge)
            end
        end
    end
    return n
end

local function MiniOverlayDraw(db, pmap, px, py, W, H, cs, sn, halfW, halfH, radius, edge)
    local farmOn, patrolOn = not not db.rxpOverlayFarm, not not db.rxpOverlayPatrol
    if not (farmOn or patrolOn) or not mini then
        MiniOverlayRelease()
        return
    end
    ovMLineN = 0
    ovNearSq = math.huge
    local alpha = tonumber(db.rxpOverlayAlpha) or 0.8
    if alpha < 0.2 then alpha = 0.2 elseif alpha > 1 then alpha = 1 end
    local thick = 2.0
    local RXP = ns.GetRXP()
    local guide = RXP and RXP.currentGuide
    local steps = guide and guide.steps
    local at = (steps and #steps > 0) and ActiveIndex() or nil
    if not at then
        MiniOverlayRelease()
        return
    end
    local future = tonumber(db.rxpMapFuture) or 0
    if future < 0 then future = 0 end
    -- The same quota the world map pass counts: SHAPES, not steps -- the
    -- glass used to stop after six raw steps and draw nothing at all while
    -- Upcoming Markers read 6.
    local drawn, futureShapes = 0, 0
    local si = at
    local limit = math.min(#steps, at + 39)
    while si <= limit do
        if si > at and futureShapes >= future then break end
        local step = steps[si]
        if step and not step.skip and not step.completed and type(step.elements) == "table" then
            local before = drawn
            for i = 1, #step.elements do
                local el = step.elements[i]
                local kind = OverlayKind(el)
                if kind == "farm" and not farmOn then kind = nil end
                if kind == "patrol" and not patrolOn then kind = nil end
                if kind then
                    local n = MiniOverlayProject(el, pmap, px, py, W, H, cs, sn,
                        halfW, halfH, radius, edge)
                    if n >= 2 then
                        local cr, cg, cb, ca = OVColor(db, kind)
                        DrawOverlayShape(ovMLineMaker, mini, kind, n,
                            thick, cr, cg, cb, alpha * (ca or 1), true, true)
                        drawn = drawn + 1
                    end
                end
            end
            -- The circuit written as gotos -- the common #loop shape in the
            -- Forever guides (the map pass draws it too): three or more of
            -- the step's own goto points, closed, mint. Without this branch
            -- the glass read "shapes=none" all day while the map drew five.
            local lkind = step.loop and LoopKind(step) or nil
            local lstyle = lkind and OV_LOOP_STYLE[lkind] or nil
            if lstyle and ((lstyle == "farm" and farmOn)
                    or (lstyle == "patrol" and patrolOn)) then
                local n = 0
                for i = 1, #step.elements do
                    local el = step.elements[i]
                    if type(el) == "table" and not el.skip and not el.completed then
                        local tag = type(el.tag) == "string" and el.tag:lower() or ""
                        if tag:find("goto", 1, true) then
                            local id, x, y = Spot(el)
                            if id then
                                local rx, ry = ReProject(id, x, y, pmap)
                                if rx and ry then
                                    n = MiniOverlayPut(rx, ry, n, px, py, W, H, cs, sn,
                                        halfW, halfH, radius, edge)
                                end
                            end
                        end
                    end
                end
                if n >= 3 then
                    local cr, cg, cb, ca = OVColor(db, lstyle)
                    DrawOverlayShape(ovMLineMaker, mini, lstyle, n,
                        thick, cr, cg, cb, alpha * (ca or 1), true, true)
                    drawn = drawn + 1
                end
            end
            if si > at then futureShapes = futureShapes + (drawn - before) end
        end
        si = si + 1
    end
    for i = ovMLineN + 1, ovMLineMax do if ovMLine[i] then ovMLine[i]:Hide() end end
    ovMLineMax = ovMLineN
    M.overlayMiniDrawn = drawn
    M.overlayMiniNear = (ovNearSq < math.huge) and math.sqrt(ovNearSq) or nil
end

function M.RefreshMini()
    local db = DB()
    if not (db and db.rxpMiniRoute) then
        MiniRelease()
        return
    end
    local mm = _G.Minimap
    if not (mm and mm.IsShown and mm:IsShown()) then
        MiniRelease("minimap hidden")
        return
    end
    local pmap, px, py, anchorCached = PlayerAnchor()
    if not pmap then
        MiniRelease("no player map")
        return
    end
    if not (px and py) then
        MiniRelease("no player position")
        return
    end
    local W, H = MapYardScale(pmap)
    if not (W and H) then
        MiniRelease("no map scale")
        return
    end
    -- The target is OPTIONAL from here: the shapes at the end of the pass
    -- need only the player's position, and "no target yet" is RestedXP's
    -- NORMAL state between two steps -- an early exit here used to take
    -- the glass down before that pass ever ran, so the shapes it owed
    -- never appeared while the status kept explaining only the route. A
    -- ghost's target is its body: while dead the corpse takes the arrow's
    -- place, one straight span, no chain, and the guide's shapes come
    -- down with the guide.
    -- The body takes priority over the guide while the player is a
    -- ghost: a step's target cannot be walked to from beyond the veil,
    -- and the corpse gets the arrow first for exactly
    -- that reason. Alive, CorpseSpot costs one boolean and answers nil.
    local corpseMap, cRawX, cRawY = CorpseSpot()
    local corpse = corpseMap ~= nil
    local targetID, rawX, rawY
    if corpse then
        targetID, rawX, rawY = corpseMap, cRawX, cRawY
    else
        targetID, rawX, rawY = CurrentSpot()
    end
    local tx, ty
    if targetID then tx, ty = ReProject(targetID, rawX, rawY, pmap) end
    local noRoute
    if not targetID then
        noRoute = "no target yet"
    elseif not tx then
        noRoute = "target off this map"
    end
    -- The bearing, in yards: the map's own steps on each axis, scaled by
    -- what each axis really measures. x runs east, y runs south, so north
    -- is the negated y step. The length of this vector is the distance as
    -- well -- one pair of numbers drives both the direction and how far
    -- out along it the marker sits.
    local east, north, dist
    if not noRoute then
        east = (tx - px) * W
        north = (py - ty) * H
        dist = math.sqrt(east * east + north * north)
        if not (dist == dist and dist >= 0 and dist < 1000000) then
            east, north, dist = nil, nil, nil
            noRoute = "no distance"
        end
    end

    EnsureMini(mm)
    if not mini or mini:GetParent() ~= mm then
        MiniRelease("no minimap frame")
        return
    end
    local halfW, halfH = mini:GetWidth() / 2, mini:GetHeight() / 2
    if not (halfW > 0 and halfH > 0) then
        MiniRelease("minimap has no size")
        return
    end

    -- "Rotate minimap" turns the minimap's TEXTURE, not this frame, so the
    -- vector is turned here instead. GetPlayerFacing() answers NORTH = 0
    -- AND COUNTERCLOCKWISE -- Plumber's DirectionArrow documents it in so
    -- many words ("North = 0, counterclockwise"), HandyNotes_MapNotes sets
    -- a north-pointing arrow's rotation straight from it, and RestedXP's
    -- own arrow only points right under that reading. So facing the target
    -- SUBTRACTS nothing here: the turn is by -facing, spelled out below.
    -- Instances can restrict the call, and MinimapCompassTexture carries
    -- the same value for exactly that reason (other minimap skins read it
    -- as the stand-in); either is only consulted while the glass turns.
    local cs, sn = 1, 0
    if type(GetCVar) == "function" then
        local ok, rot = pcall(GetCVar, "rotateMinimap")
        if ok and rot == "1" then
            local f
            if type(GetPlayerFacing) == "function" then
                local okF, v = pcall(GetPlayerFacing)
                if okF and type(v) == "number" and v == v then f = v end
            end
            if not f then
                local c = _G.MinimapCompassTexture
                if c and type(c.GetRotation) == "function" then
                    local okC, v = pcall(c.GetRotation, c)
                    if okC and type(v) == "number" and v == v then f = v end
                end
            end
            if f then cs, sn = math.cos(f), math.sin(f) end
        end
    end
    -- east/north (y up) -> screen (x right, y up) at bearing + facing:
    -- the target lands where the player is LOOKING when the two agree.
    local bx, by
    if not noRoute then
        bx = east * cs + north * sn
        by = north * cs - east * sn
    end

    -- Its share of the glass: what fraction of the world under the minimap
    -- this distance is, times the half of the frame that world reaches to.
    -- With no radius the client will part with, distance is unknowable and
    -- only direction is honest -- so the target goes to the rim, where
    -- anything out of reach belongs.
    local radius = MiniRadius(mm)
    local msize = MarkerSize(1)   -- the world map's marker at zoom 1: ~10 px
    local edge = math.max(8, math.min(halfW, halfH) - (msize / 2 + 3))
    local ux, uy, pd, inside, ex, ey
    if not noRoute then
        if radius then
            ux, uy = bx / radius * halfW, by / radius * halfH
        else
            local l = math.sqrt(bx * bx + by * by)
            if l > 0 then ux, uy = bx / l * edge, by / l * edge else ux, uy = 0, 0 end
        end
        pd = math.sqrt(ux * ux + uy * uy)
        -- Inside the glass, or ON it: everything this pass draws lives within
        -- the inscribed circle, the one shape that is true on a round minimap
        -- and still safe on a square one.
        inside = pd <= edge
        ex, ey = ux, uy
        if not inside and pd > 0 then ex, ey = ux / pd * edge, uy / pd * edge end
        if (radius and pd < 4) or (not radius and dist < 1) then
            -- Under the player's feet: four pixels of line is not a route, and
            -- a marker at the centre would sit under the player's own arrow.
            -- The shapes still have a place on the glass -- only the ROUTE
            -- has nowhere to go.
            noRoute = "at your feet"
        end
    end

    mini:Show()
    mlineN, mchevN, mmarkN = 0, 0, 0
    -- The corpse stroke's pool counts from zero with the rest.
    mclLineN = 0
    M.miniCorpseLineDrawn = nil
    -- The skull belongs to the previous pass until this one says
    -- otherwise: a player who resurrects mid-run keeps no skull from the
    -- run that just ended.
    if miniSkull then miniSkull:Hide() end

    if noRoute then
        -- No goal to point at: the route pools come down, their reason
        -- stays in the state line, and the shapes at the end still get
        -- their pass -- one refresh owns both layers, and this exit used
        -- to take the glass down before that pass ever ran. (A corpse run
        -- lands here only when the body reprojects onto another map, and
        -- its shapes are the guide's, so they go with the guide.)
        for i = 1, mlineMax do if mline[i] then mline[i]:Hide() end end
        for i = 1, mchevMax do if mchev[i] then mchev[i]:Hide() end end
        for i = 1, mmarkMax do
            local m = mmark[i]
            if m then m.ring:Hide(); m.center:Hide() end
        end
        mlineMax, mchevMax, mmarkMax = 0, 0, 0
        M.miniChainWanted, M.miniChainDrawn = 0, 0
        if corpse then
            MiniOverlayRelease()
        else
            MiniOverlayDraw(db, pmap, px, py, W, H, cs, sn, halfW, halfH, radius, edge)
        end
        M.miniState = noRoute
        return
    end

    local r, g, b
    if corpse then
        -- Blood red, the run's own colour -- the world map's, same
        -- numbers, so the two surfaces cannot disagree about the dead.
        r, g, b = CORPSE_LINE[1], CORPSE_LINE[2], CORPSE_LINE[3]
    else
        r, g, b = ns.ThemeAccent()
    end
    -- The same slider, the same numbers at weight 1: the minimap's stroke
    -- IS the world map's at zoom 1, so one control moves both.
    local weight = db.rxpMapThickness or 1
    local thick, halo, chevSize = 2.6 * weight, 1.6 * weight, 11
    local flowSpeed = db.rxpMapFlowSpeed or 0.5
    if corpse then
        -- The corpse stroke comes out of ITS OWN pool, hosted on the
        -- `mini` overlay -- the same frame that draws every chevron and
        -- marker on the glass (see MCLine above). It passes over the
        -- game's tomb pin; every host tried UNDER it sank under the
        -- decor instead, so visible-over-tomb is the settled rule. The
        -- line still runs the WHOLE way -- player to body, no gap.
        DrawSegment(MCLine, mm, 0, 0, ex, ey, thick, halo, r, g, b, 1)
        M.miniCorpseLineDrawn = mclLineN
        -- The skull instead of the chevrons, ONE of it, travelling from
        -- the player out towards the body -- and no bullseye over that
        -- place: the game's own tombstone marks it while the player is
        -- a ghost.
        if not miniSkull then
            miniSkull = mini:CreateTexture(nil, "OVERLAY", nil, 7)
            miniSkull:SetTexture(CORPSE_SKULL)
        end
        CorpseSkull(miniSkull, mini, 0, 0, ex, ey, 14, flowSpeed)
    else
        DrawSegment(MLine, mini, 0, 0, ex, ey, thick, halo, r, g, b, 1)
        -- White chevrons as on the map. The spacing thresholds below are
        -- the world map's, in pixels, and a minimap line never reaches 42
        -- of them: 18 is the shortest span a chevron still reads a flow.
        FlowChevrons(MChev, mini, 0, 0, ex, ey, chevSize, 1, 1, 1, 1, flowSpeed, 18)
        MMarker(ex, ey, msize, r, g, b, 1, true)
    end

    -- The minimap draws the CURRENT target alone. The upcoming steps used
    -- to ring here too -- extra dots on a glass only a few hundred pixels
    -- across, and they read as noise in play -- so the chain lives on the
    -- world map now, where "Upcoming markers" puts it, and nowhere else.
    -- The pass still answers the status: no rings asked, none drawn.
    M.miniChainWanted, M.miniChainDrawn = 0, 0

    -- The pass is over: drop what it did not take this time.
    for i = mlineN + 1, mlineMax do if mline[i] then mline[i]:Hide() end end
    for i = mchevN + 1, mchevMax do if mchev[i] then mchev[i]:Hide() end end
    for i = mmarkN + 1, mmarkMax do
        local m = mmark[i]
        if m then m.ring:Hide(); m.center:Hide() end
    end
    mlineMax, mchevMax, mmarkMax = mlineN, mchevN, mmarkN
    for i = mclLineN + 1, mclLineMax do if mclLine[i] then mclLine[i]:Hide() end end
    mclLineMax = mclLineN
    -- The guide's own shapes on the glass -- the same pass, after the
    -- route, under it (sublevel 2 against 5): one refresh owns both.
    -- The guide's shapes, last of the pass -- unless the player is a
    -- ghost: then the guide is not being walked, its shapes come down
    -- and the corpse route above is the only thing on the glass (corpse
    -- mode takes the rest of it down).
    if corpse then
        MiniOverlayRelease()
    else
        MiniOverlayDraw(db, pmap, px, py, W, H, cs, sn, halfW, halfH, radius, edge)
    end
    M.miniState = corpse and "corpse run" or "drawn"
end

-- Why is nothing on the minimap? One line, every stage, so a blank glass
-- can be read rather than guessed at. /euirxp status prints it while the
-- minimap route is on.
function M.MiniDiagnose()
    local db = DB()
    local parts = {}
    local function say(k, v) parts[#parts + 1] = k .. "=" .. tostring(v) end
    say("on", not not (db and db.rxpMiniRoute))
    say("state", M.miniState or "-")
    local mm = _G.Minimap
    say("minimap", not not mm)
    if mm then
        local w, h = mm:GetWidth(), mm:GetHeight()
        say("size", (type(w) == "number" and type(h) == "number")
            and ("%.0fx%.0f"):format(w, h) or "?")
        local r = MiniRadius(mm)
        say("viewRadius", r and string.format("%.0f", r) or "?")
    end
    local pmap
    if C_Map and type(C_Map.GetBestMapForUnit) == "function" then
        local ok, id = pcall(C_Map.GetBestMapForUnit, "player")
        if ok then pmap = id end
    end
    say("playerMap", pmap or "?")
    local amap, _, _, acached = PlayerAnchor()
    say("anchor", amap and ((acached and "cached ") or "live ") .. tostring(amap) or "none")
    if pmap then
        local sw, sh = MapYardScale(pmap)
        say("mapScale", (sw and sh) and ("%.0f/%.0f yd"):format(sw, sh) or "?")
    end
    if type(GetCVar) == "function" then
        local okR, rv = pcall(GetCVar, "rotateMinimap")
        say("rotateMinimap", okR and tostring(rv) or "?")
    end
    local targetID = CurrentSpot()
    local dead = IsCorpseRun()
    local corpseID
    if dead then corpseID = CorpseSpot() end
    if corpseID then targetID = corpseID end
    say("targetMap", targetID or "?")
    say("corpse", dead and (corpseID and "run to body" or "body not found")
        or "alive")
    say("build", M.BUILD)
    if dead then
        say("corpseLine", M.miniCorpseLineErr
            or ((M.miniCorpseLineDrawn or 0) > 0
                and (M.miniCorpseLineDrawn .. " tex OVERLAY/2 on route mini via="
                    .. tostring(M.miniCorpseLineHow or "?"))
                or "0 tex (branch not reached)"))
        say("mmRegions", LayerDump(mm))
        -- Where the minimap's own children stand: if the tomb is a frame,
        -- its level shows here, and the stroke's host can be compared
        -- against it in the very same capture.
        local okK, kv = pcall(KidDump, mm)
        say("mmKids", okK and kv or ("? " .. tostring(kv)))
    end
    say("segments", mlineN > 0 and tostring(mlineN) or "none")
    say("markers", mmarkN > 0 and tostring(mmarkN) or "none")
    say("chain", (M.miniChainWanted or 0) > 0
        and (tostring(M.miniChainDrawn or 0) .. "/" .. tostring(M.miniChainWanted))
        or "off")
    -- The shape layer in THREE numbers, because one of them lied: the pass
    -- used to report the strokes it laid down and nothing else, so a guide
    -- whose farm circuit is 500 yd away -- drawn on the world map, out of
    -- reach of the glass -- read "shapes=none" exactly like a pass that
    -- classified nothing at all. Classified, strokes, and how far the
    -- nearest point of any of them sits: the three together say which.
    say("shapes", M.overlayMiniDrawn ~= nil and tostring(M.overlayMiniDrawn) or "-")
    say("strokes", ovMLineN > 0 and tostring(ovMLineN) or "none")
    say("nearest", M.overlayMiniNear and string.format("%.0f yd", M.overlayMiniNear) or "-")
    return table.concat(parts, "  ")
end

-- Settings and accent changes go straight through: there is no point
-- waiting for the next tick when the answer is "redraw now".
function M.Refresh()
    if On() then M.RefreshMap() else Release() end
    if MiniOn() then M.RefreshMini() else MiniRelease() end
end

-- The ticker only costs anything while one of the two routes is on:
-- outside that, a comparison and a subtraction per frame, and nothing is
-- built or touched. The world map pass keeps its own guard inside it (the
-- map closed means Release), so both surfaces share one cadence.
local tick, elapsed = CreateFrame("Frame"), 0
tick:SetScript("OnUpdate", function(_, dt)
    if not (On() or MiniOn()) then
        elapsed = 0
        return
    end
    elapsed = elapsed + dt
    if elapsed < TICK then return end
    elapsed = 0
    if On() then M.RefreshMap() end
    if MiniOn() then M.RefreshMini() end
end)
