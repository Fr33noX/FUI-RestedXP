-- How much world the minimap shows, as a radius in YARDS: the one number
-- that turns a distance into a place on the glass. The client answers it
-- outright when it can. The fallback is the yard size of each zoom step --
-- the outdoor/indoor pair Blizzard keeps in two cvars of its own, the
-- minimap being outdoors when it sits at the zoom "minimapZoom" names.
local MINI_ZOOM = {
    outdoor = { [0] = 233.33, [1] = 200, [2] = 166.67, [3] = 133.33, [4] = 100, [5] = 66.67 },
    indoor = { [0] = 150, [1] = 120, [2] = 90, [3] = 60, [4] = 40, [5] = 25 },
}
local function MiniRadius(mm)
    if C_Minimap and type(C_Minimap.GetViewRadius) == "function" then
        local ok, r = pcall(C_Minimap.GetViewRadius)
        if ok and type(r) == "number" and r == r and r > 0 and r < 1000000 then return r end
    end
    if type(mm.GetZoom) ~= "function" then return nil end
    local ok, zoom = pcall(mm.GetZoom, mm)
    if not ok or type(zoom) ~= "number" or zoom ~= zoom then return nil end
    zoom = math.floor(zoom + 0.5)
    local mode = "outdoor"
    if type(GetCVar) == "function" then
        local okC, cv = pcall(GetCVar, "minimapZoom")
        local outside = okC and tonumber(cv) or nil
        if outside and zoom ~= outside then mode = "indoor" end
    end
    local row = MINI_ZOOM[mode]
    return row[math.max(0, math.min(5, zoom))]
end

