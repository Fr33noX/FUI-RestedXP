local OV_DBKEY = {
    farm = "rxpOverlayFarm",
    patrol = "rxpOverlayPatrol",
    search = "rxpOverlaySearch",
}
local function OVColor(db, kind)
    local p = OV_DBKEY[kind]
    local r = p and db and db[p .. "R"] or nil
    local g = p and db and db[p .. "G"] or nil
    local b = p and db and db[p .. "B"] or nil
    if type(r) == "number" and type(g) == "number" and type(b) == "number" then
        local a = p and db and db[p .. "A"] or nil
        return r, g, b, (type(a) == "number" and a or 1)
    end
    local base = OV_COLORS[kind]
    if base then return base[1], base[2], base[3], base[4] or 1 end
    return 1, 1, 1, 1
end
