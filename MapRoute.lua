-- Chevrons running along a segment: a direction, not a bar. A density
-- guard, in canvas pixels: nothing under minLen, one cue on a short span,
-- three on a long one, never a flood. minLen is 42 on the bearing to the
-- current target and 24 on the chain, where the segments run shorter. The
-- phase advances with time so the route reads as motion, at its 0.5 speed
-- rather than the old 1 -- twice the travel per pass is what made the flow
-- look like it was stuttering.
-- `nextChev` is the pool the chevrons come out of: the world map and the
-- minimap draw the same flow with their own frames, so the caller hands
-- over its own maker rather than the drawing being written twice. The
-- world map now flows along the CURVE instead (FlowPathChevrons, same
-- density and phase); this straight version is the minimap's -- whose
-- spans are short and rim-clamped, where a bend would only bow the line
-- off the glass.
local function FlowChevrons(nextChev, parent, x1, y1, x2, y2, size, r, g, b, a, speed, minLen)
    local dx, dy = x2 - x1, y2 - y1
    local len = math.sqrt(dx * dx + dy * dy)
    if len < (minLen or 42) then return end
    local ang = math.atan2(dy, dx)
    local n = (len < 72) and 1 or ((len < 145) and 2 or 3)
    local phase = ((GetTime() or 0) * 0.42 * (speed or 1)) % 1
    for i = 1, n do
        local c = nextChev()
        local t = 0.20 + ((phase + (i - 1) / n) % 1) * 0.60
        c:ClearAllPoints()
        c:SetPoint("CENTER", parent, "CENTER", x1 + dx * t, y1 + dy * t)
        c:SetWidth(size)
        c:SetHeight(size)
        c:SetRotation(ang)
        c:SetVertexColor(r, g, b, a)
        c:Show()
    end
end
-- The corpse run's ONE indicator: the raid skull travelling the line
-- from the player towards the body, once per cycle, fading in and out
-- as it goes -- so the animation ever shows a SINGLE skull where the
-- chevrons showed a row of them. The phase runs on the chevrons' own
-- clock, so Flow Speed moves this too, and both ends fade to nothing so
-- the skull never sits on top of the player or of the body itself.
local function CorpseSkull(tex, parent, x1, y1, x2, y2, size, speed)
    if not tex then return end
    local phase = ((GetTime() or 0) * 0.42 * (speed or 1)) % 1
    local a = math.sin(phase * math.pi)
    tex:ClearAllPoints()
    tex:SetPoint("CENTER", parent, "CENTER",
        x1 + (x2 - x1) * phase, y1 + (y2 - y1) * phase)
    tex:SetWidth(size)
    tex:SetHeight(size)
    -- White on the blood red line, the rule the chevrons follow: tinted
    -- red it would sink into its own stroke.
    tex:SetVertexColor(1, 1, 1, a)
    tex:Show()
end

