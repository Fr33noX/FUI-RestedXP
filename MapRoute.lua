-- A marker drawn as a bullseye -- an
-- outer band, a dark separator, an inner band -- with a dot laid over it,
-- both textures tinted in the accent color. The dark bands baked into the
-- textures are what keep the rings apart: SetVertexColor multiplies them
-- by the tint, so they stay dark whatever the accent is. This replaces the
-- circle spelled out of eight squares, which read as a cluster of blobs at
-- every zoom.
-- `dot` decides the centre dot inside the ring: it marks the step the
-- player is ON. Future markers are rings only -- a dot on every waypoint
-- does turn a chain into a string of beads. Both textures stay pooled
-- either way; only the show flag differs.
local function Marker(parent, x, y, size, r, g, b, a, dot)
    markN = markN + 1
    local m = markers[markN]
    if not m then
        m = {}
        -- Sublevel 6: above the segments (5), below the chevrons (7).
        -- Without an explicit sublevel the pool hands frames out in the
        -- order the pass asks for them, so "who draws over whom" would
        -- depend on which segment happened to be drawn first that tick.
        m.ring = overlay:CreateTexture(nil, "OVERLAY", nil, 6)
        m.ring:SetTexture("Interface\\AddOns\\" .. ADDON .. "\\Textures\\rxp-map-ring.png")
