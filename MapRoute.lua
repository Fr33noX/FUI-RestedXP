-- A position read on one map, brought into another. Two maps only share
-- positions through a continent, so that is the pivot; maps that share
-- none have no honest place to put the point and return nil.
local function ReProject(id, x, y, displayID)
    if id == displayID then return x, y end
    if not (C_Map and C_Map.GetWorldPosFromMapPos and C_Map.GetMapPosFromWorldPos) then return nil end
    -- `id` comes from the guide's data, not from the client, and the C_Map
    -- calls validate their arguments: a map id this client does not know
    -- raises instead of answering nil. Left bare that would throw from the
    -- update ticker, once per frame, for as long as the map is open.
    local okA, continentID, world = pcall(C_Map.GetWorldPosFromMapPos, id, { x = x, y = y })
    if not (okA and continentID and world) then return nil end
    local okB, _, pos = pcall(C_Map.GetMapPosFromWorldPos, continentID, world, displayID)
    if not (okB and pos) then return nil end
    local px, py
    if type(pos.GetXY) == "function" then px, py = pos:GetXY() else px, py = pos.x, pos.y end
    if type(px) ~= "number" or type(py) ~= "number" then return nil end
    if IsSecret(px) or IsSecret(py) then return nil end
    -- The reprojection can land a hair outside the parchment; pinned to the
    -- edge is honest ("over there"), blank is not.
    return math.min(math.max(px, 0), 1), math.min(math.max(py, 0), 1)
end

-- The canvas every map drawing is parented to. This is Blizzard's own
-- frame, found the way the map itself finds it, with a fallback for clients
-- that shape the scroll container differently.
local function Canvas()
    local wm = _G.WorldMapFrame
    if not wm then return nil end
    local sc = wm.ScrollContainer
    if sc then
        if sc.Child then return sc.Child end
        if type(sc.GetScrollChild) == "function" then
            local child = sc:GetScrollChild()
            if child then return child end
        end
    end
    return wm
end

-- Canvas coordinates: origin at the canvas centre, y running down. This is
-- the map's own convention for its line widget, so a line drawn here stays
-- put through zoom and pan instead of drifting across the parchment.
local function Cx(x, w) return x * w - w / 2 end
local function Cy(y, h) return -y * h + h / 2 end

-- How much thicker to draw. We draw in canvas pixels, and the canvas grows
-- as the map zooms in: a fixed 4 px line is a thread on a zoomed zone map
-- and a slab on a continent pulled all the way out. Reading the map's own
-- scale keeps the route the same weight on screen at any zoom.
--
-- Two readings do it: the map's TYPE, because a
-- continent seen from far up needs a heavier line than the zone you stand
-- in, and the canvas scale, because zooming in must not thin the route.
-- The old version read only the scale, so the widest view -- a continent --
-- ended up with the thinnest line of all.
local function ThicknessBoost(mapID)
    local boost = 1
    if mapID and C_Map and C_Map.GetMapInfo then
        local ok, info = pcall(C_Map.GetMapInfo, mapID)
        if ok and type(info) == "table" and type(info.mapType) == "number" then
            if info.mapType <= 1 then
                boost = 1.80        -- the whole world at once
            elseif info.mapType == 2 then
                boost = 1.55        -- one continent
            end
        end
    end
    local sc = _G.WorldMapFrame and _G.WorldMapFrame.ScrollContainer
    if not (sc and type(sc.GetCanvasScale) == "function") then return boost end
    local s = sc:GetCanvasScale()
    if type(s) ~= "number" or s <= 0 or s >= 1 then return boost end
    return math.max(boost, math.min(2.05, 1 / math.sqrt(s)))
end

-- The marker's size in canvas pixels: a fixed 14 px that the map's zoom
-- SHRINKS, which is what keeps a bullseye readable on a continent without
-- it blotting out the terrain. The old 16*boost did the opposite -- 16 px
-- up close, 26 px zoomed out -- and the 26 px ring was a blob on screen.
local function MarkerSize(boost)
    local k = math.max(0.42, math.min(0.72, 0.72 / (boost ^ 0.78)))
    return 14 * k
end

