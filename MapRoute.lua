-- The first string among a list of return values. The quest APIs answer
-- in different orders on different builds of this client -- title first on
-- one, id first on another -- so the shape of the answer is read rather
-- than its position.
local function FirstString(a, b, c, d)
    if type(a) == "string" and a ~= "" then return a end
    if type(b) == "string" and b ~= "" then return b end
    if type(c) == "string" and c ~= "" then return c end
    if type(d) == "string" and d ~= "" then return d end
    return nil
end

-- The first value that can honestly be a quest LEVEL: a quest id is a
-- number too, and a far larger one, so anything outside 1..200 is not a
-- level on any client this ships to.
local function FirstLevel(a, b, c, d)
    local function take(v)
        local n = tonumber(v)
        if n and n >= 1 and n <= 200 then return n end
        return nil
    end
    return take(a) or take(b) or take(c) or take(d)
end

local function QuestID(e)
    if type(e) ~= "table" then return nil end
    local qid = tonumber(e.questId)
    if not qid and type(e.questIds) == "table" then qid = tonumber(e.questIds[1]) end
    if not qid and type(e.quests) == "table" then qid = tonumber(e.quests[1]) end
    return qid
end

local function QuestTitle(qid)
    if type(C_QuestLog) ~= "table" then return nil end
    -- The direct lookup first: it answers for a quest the player has not
    -- accepted yet, which is exactly the moment a guide says "accept this".
    if type(C_QuestLog.GetTitleForQuestID) == "function" then
        local ok, t = pcall(C_QuestLog.GetTitleForQuestID, qid)
        if ok and type(t) == "string" and t ~= "" then return t end
    end
    if type(C_QuestLog.GetQuestInfo) == "function" then
        local ok, a, b, c, d = pcall(C_QuestLog.GetQuestInfo, qid)
        if ok then return FirstString(a, b, c, d) end
    end
    return nil
end

-- Where the quest stands: its level, its index in the log, whether it is
-- ready to turn in, and whether it is already done. Each answer has more
-- than one route into it and none of them is guaranteed, so every route is
-- optional and the misses cost nothing.
local function QuestState(qid)
    local level, idx, ready, done
    if type(C_QuestLog) == "table" then
        local getter = (type(C_QuestLog.GetLogIndexForQuestID) == "function"
            and C_QuestLog.GetLogIndexForQuestID)
            or (type(GetQuestLogIndexByID) == "function" and GetQuestLogIndexByID)
        if getter then
            local ok, i = pcall(getter, qid)
            if ok and type(i) == "number" and i > 0 then idx = i end
        end
        if idx then
            if type(C_QuestLog.GetInfo) == "function" then
                local ok, info = pcall(C_QuestLog.GetInfo, idx)
                if ok and type(info) == "table" then
                    level = tonumber(info.level)
                    if info.isComplete == true or info.isComplete == 1 then ready = true end
                end
            end
            if not level and type(GetQuestLogTitle) == "function" then
                local ok, _, lvl = pcall(GetQuestLogTitle, idx)
                if ok then level = FirstLevel(lvl) end
            end
        end
        if not level and type(C_QuestLog.GetQuestInfo) == "function" then
            local ok, a, b, c, d = pcall(C_QuestLog.GetQuestInfo, qid)
            if ok then level = FirstLevel(a, b, c, d) end
        end
        if type(C_QuestLog.IsQuestFlaggedCompleted) == "function" then
            local ok, v = pcall(C_QuestLog.IsQuestFlaggedCompleted, qid)
            if ok and v then done = true end
        end
    end
    return level, idx, ready, done
end

-- The quest log's own colouring: grey once trivial, green below you,
-- yellow in range, orange above you. The API answers with a colour table
-- on some builds and with three plain numbers on others; both are read,
-- and a refusal falls back to the yellow of "could not tell".
local function DifficultyColor(level)
    if type(level) ~= "number" or type(GetQuestDifficultyColor) ~= "function" then
        return 0.95, 0.82, 0.41
    end
    local ok, a, b, c = pcall(GetQuestDifficultyColor, level)
    if ok and type(a) == "table" then
        if type(a.r) == "number" and type(a.g) == "number" and type(a.b) == "number" then
            return a.r, a.g, a.b
        end
        if type(a[1]) == "number" then return a[1], a[2] or 0.95, a[3] or 0.82 end
    elseif ok and type(a) == "number" and type(b) == "number" then
        return a, b, (type(c) == "number" and c) or 0.41
    end
    return 0.95, 0.82, 0.41
end

-- The instance the marker sits in, if it sits in one: map type 4 is this
-- client's dungeon/raid type, so an ordinary zone never grows this line
-- and a dungeon always does.
local function InstanceName(e)
