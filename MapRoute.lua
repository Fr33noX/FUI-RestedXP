-- What a shape calls itself in the tooltip. Declared up here because
-- TipEnter -- below -- prints it, and a local declared further down the
-- file would not exist yet when this function is compiled. The overlay
-- pass draws the shapes; this is only the name it answers to.
local OV_KIND_LABEL = {
    farm = "Farm route",
    patrol = "Patrol path",
    search = "Search area",
    interact = "Interact route",
}

local function TipEnter(self)
    if not GameTooltip then return end
    -- The master switch. The pass stops BUILDING the marker buttons while
    -- this is off, so the mouse reaches the map underneath instead; this
    -- guard only covers the hover already in flight when it was flipped.
    if not TipShow("rxpTipOn") then return end
    local e = self.el
    local ord = self.ordinal or 1
    GameTooltip:SetOwner(self, "ANCHOR_CURSOR")
    GameTooltip:ClearLines()
    -- The step this marker belongs to. The pass hands over the guide's own
    -- step number when it has one; a marker drawn for the current target
    -- carries no number of ours, so the element's step is asked instead --
    -- it is the same object RestedXP's arrow reads its title from.
    local st = (type(e) == "table") and e.step or nil
    local stepObj = (type(st) == "table") and st or nil
    local stepNo = self.step or (stepObj and tonumber(stepObj.index))
        or (type(st) == "number" and st) or nil
    if TipShow("rxpTipHeader") then
        -- Where this marker sits in the chain, and which step it belongs to.
        -- A shape is not a marker: it answers with what KIND of ground it
        -- is, since "Kill Razormane Scouts" on its own says nothing about a
        -- mint circuit drawn over the hillside.
        local head
        if type(self.kind) == "string" then
            head = OV_KIND_LABEL[self.kind] or "Route"
        else
            head = ord == 1 and "Current target" or ("Next +" .. tostring(ord - 1))
        end
        if stepNo then head = head .. "  -  step " .. tostring(stepNo) end
        GameTooltip:AddLine(head, 1.00, 0.80, 0.20)
    end

    -- Two switches over ONE list, with DISJOINT ownership: the TITLE owns
    -- the step's headline -- the guide's own title when it has one,
    -- otherwise its first instruction line (RestedXP names few of its
    -- steps, and a switch cutting only a real title did nothing on almost
    -- every one) -- and the INSTRUCTIONS own what follows it. So neither
    -- switch can show the other's line: with the title off the headline is
    -- simply not shown, it is not handed over to Instructions, and nothing
    -- is ever printed twice.
    local all = Instructions(e, stepObj)
    local head = (type(e) == "table") and OneLine(e.title) or nil
    if not head and stepObj then
        head = OneLine(stepObj.arrowtext) or OneLine(stepObj.title)
    end
    if not head then head = all[1] end
    -- A line equal to the headline belongs to the title switch alone, so
    -- Instructions skips it wherever it sits in the list -- and with the
    -- title off, that line is shown by nobody rather than by Instructions.
    if TipShow("rxpTipTitle") and head then
        GameTooltip:AddLine(head, 1.00, 0.93, 0.72, true)
    end
    if TipShow("rxpTipText") then
        -- The main event: what this step asks the player to DO -- "Kill
        -- Mottled Boars" -- read off the step's text lines, because that is
        -- where RestedXP keeps them.
        for i = 1, #all do
            if all[i] ~= head then GameTooltip:AddLine(all[i], 1, 1, 1, true) end
        end
    end

    -- What the marker points at. RestedXP only names the target of the
    -- step it is actively ON, so a marker further down the chain often
    -- carries neither name and this pair of lines simply stays away.
    if TipShow("rxpTipTarget") and type(e) == "table" then
        local npc = OneLine(e.name)
        if npc then
            GameTooltip:AddLine("NPC: " .. npc, 0.55, 0.85, 1.00, true)
        else
            local item = OneLine(e.itemName)
            if item then GameTooltip:AddLine("Item: " .. item, 0.55, 0.85, 1.00, true) end
        end
    end

    -- The kind of step, in words, with RestedXP's own icon before it.
    if TipShow("rxpTipType") and type(e) == "table" and type(e.tag) == "string"
        and e.tag ~= "" and not IsSecret(e.tag) then
        local label = TypeLabel(e.tag)
        if label ~= "" then
            GameTooltip:AddLine(TypeIcon(e.tag) .. "Type: " .. label,
                0.90, 0.90, 0.90, true)
        end
    end

    -- How far, which way, roughly when: colored like the arrow card by
    -- distance (green close, yellow near, red far). The distance is the
    -- ROUTE distance the pass measured -- cumulative along the chain for
    -- an upcoming marker -- so the ETA below is the time to walk there.
    if TipShow("rxpTipNav") then
        local nav, nr, ng, nb = NavLine(drawnMap, self.mx, self.my, self.cum)
        if nav then GameTooltip:AddLine(nav, nr, ng, nb) end
    end

    -- The quest behind it: title, level in its difficulty colour, where it
    -- stands in the log, the objectives with their counters, the id.
    if TipShow("rxpTipQuest") then QuestLines(e) end

    if TipShow("rxpTipZone") then
        local inst = InstanceName(e)
        if inst then GameTooltip:AddLine("Instance: " .. inst, 0.85, 0.70, 0.45, true) end
        local zone = MapName(self.map)
        if zone then GameTooltip:AddLine(zone, 0.45, 0.75, 1.00) end
    end
    GameTooltip:Show()
end

local function TipHide()
    if GameTooltip then GameTooltip:Hide() end
end

-- One hover target per marker, sized like the marker and reaching 6 px past
-- it (hit rect insets), so a 7 px bullseye is still an easy mouse target.
-- The strata is TOOLTIP, the one guaranteed to sit above whatever the map
-- itself put under the cursor -- the map's own pins are a different strata
-- and would swallow the hover otherwise.
local function Tip(parent, x, y, size, el, stepNo, ordinal, map, cum)
    tipN = tipN + 1
    local t = tips[tipN]
    if not t then
        t = CreateFrame("Button", nil, overlay)
        t:EnableMouse(true)
        t:SetFrameStrata("TOOLTIP")
        t:SetFrameLevel(1)
        if t.SetHitRectInsets then t:SetHitRectInsets(-6, -6, -6, -6) end
        t:SetScript("OnEnter", TipEnter)
        t:SetScript("OnLeave", TipHide)
        -- Hidden under the cursor (the guide moved on): the tooltip must go
        -- with it, OnLeave never fires for a frame that simply vanished.
        t:SetScript("OnHide", TipHide)
        tips[tipN] = t
    end
    t:ClearAllPoints()
    t:SetPoint("CENTER", parent, "CENTER", x, y)
    t:SetSize(size, size)
    -- Where this marker sits on the displayed map, read back out of the
    -- canvas coordinates it was drawn from (the canvas convention runs
    -- x east, y south from its centre): the tooltip's compass points at
    -- where the marker is ON SCREEN, north up, and its distance is
    -- measured from the very coordinates the line was drawn with.
    local w, h = parent:GetWidth(), parent:GetHeight()
    if w and h and w > 0 and h > 0 then
        t.mx, t.my = (x + w / 2) / w, (h / 2 - y) / h
    else
        t.mx, t.my = nil, nil
    end
    -- cum rides along with them: the route distance to this marker as the
    -- pass measured it, nil when there is none to report.
    t.el, t.step, t.ordinal, t.map, t.cum = el, stepNo, ordinal, map, cum
    t:Show()
    return t
end

