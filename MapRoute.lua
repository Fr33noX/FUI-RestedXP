-- FUI-RestedXP MapRoute.lua
-- A route on the world map, drawn from the guide's own data: a straight
-- line from the player to RestedXP's current target, and (optionally) a
-- chain through the next few steps, in the color the Theme page picks (the
-- custom color or the live accent -- the same source as the rest of the
-- addon).
--
-- Geometry, sizes and cadence are fixed measurements: the "thin" line
-- style, a 0.5 animation speed, a 10/s map refresh, a 14 px marker. Every
-- line of code and every texture here is ours -- mkmaptex.ps1 draws them
-- from scratch, it ships nothing taken from anywhere else.
--
-- What this is NOT: a pathfinder. The client exposes no navmesh an addon
-- can read, so a route here is a bearing -- "that way" -- exactly like the
-- line RestedXP's own arrow implies. It never suggests a road to follow.
--
-- Everything is read, never written: RestedXP's arrow frame publishes the
-- element the guide is heading for, and that element carries the map id and
-- the coordinates. The route is drawn from four antialiased textures of our
-- own (bullseye ring, center dot, chevron, line -- tinted by SetVertexColor,
-- with the dark bands that separate them baked into the images), generated by
-- _blpwork/mkmaptex.ps1: drawn from scratch, never taken.
--
-- Off by default: the overlay is created on the world map's canvas, the
-- one RestedXP-adjacent surface we have never tested against a third-party
-- map styling. Turning it off removes every frame it made and leaves the map
-- exactly as it was.
--
-- Two surfaces, two switches: the world map above, and the minimap -- its
-- own overlay centred on the player, turning with "Rotate minimap", on
-- rxpMiniRoute. Both read the same numbers (the same target, the same
-- chain, the same accent, the same chevron speed) so they cannot disagree
-- about where the guide is sending you.
