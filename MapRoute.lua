local function Hide(i)
    if lines[i] then lines[i]:Hide() end
    if chevs[i] then chevs[i]:Hide() end
    if markers[i] then
        markers[i].ring:Hide()
        markers[i].center:Hide()
    end
end

-- ONE marker off, ring and dot together -- the leftovers loop of a pass
-- that drew fewer markers than the one before it. It used to call Hide,
-- which takes all three pools: lines run ahead of markers in every pass
-- (two of them per segment), so that loop was switching off segments the
-- very same pass had just drawn, one flicker whenever the chain shortened.
local function HideMarker(i)
    if markers[i] then
        markers[i].ring:Hide()
        markers[i].center:Hide()
    end
end

-- Everything off: the disabled state, and every early exit of a pass.
local function Release()
    for i = 1, math.max(lineMax, math.max(chevMax, markMax)) do Hide(i) end
    for i = 1, tipMax do if tips[i] then tips[i]:Hide() end end
    lineN, lineMax, chevN, chevMax, markN, markMax = 0, 0, 0, 0, 0, 0
    tipN, tipMax = 0, 0
    -- The chain count goes with it: left standing it would have the
    -- diagnostic reporting an old pass's markers, which is the one thing
    -- the chain figure exists to disprove.
    M.chainWanted, M.chainDrawn = nil, nil
    -- What the route ended on goes with it: a blank map that cannot say
    -- WHY it is blank is the bug this whole line exists to prevent.
    M.routeState = nil
    -- The corpse run's skull rides this same pass and comes down with it.
    if mapSkull then mapSkull:Hide() end
    -- Its stroke is on the canvas, not on this overlay: it comes down
    -- here too, or a disabled route would leave a red line on the map.
    CLineHideAll()
    -- The overlay layer rides this same pass, so it goes down with the
    -- route: same switch, same frames' lifetime, one state to read.
    OverlayRelease()
end

-- Rebuilding the pool when the canvas changes is deliberate: the map
-- recreates its scroll child on a rebuild, and frames parented to the old
-- one would silently vanish mid-session.
local function EnsureOverlay(parent)
    if overlay and overlay:GetParent() == parent then return overlay end
    Release()
    if overlay then overlay:Hide() end
    -- The pool belongs to the overlay being replaced: frames parented to a
    -- frame that is gone never draw again, so handing them out here would
    -- silently draw nothing. The tables start empty on the new overlay.
    for i = #lines, 1, -1 do lines[i] = nil end
    for i = #chevs, 1, -1 do chevs[i] = nil end
    for i = #markers, 1, -1 do markers[i] = nil end
    for i = #tips, 1, -1 do tips[i] = nil end
    -- Its texture lived on the overlay just retired (Release hid it
    -- above): the new overlay grows a new one when a run needs it.
    mapSkull = nil
    -- The corpse stroke's pool belongs to the canvas just left (Release
    -- hid its textures above): the new canvas grows new ones.
    for i = #clLine, 1, -1 do clLine[i] = nil end
    clLineN, clLineMax = 0, 0
    tipN, tipMax = 0, 0
    -- The overlay pools go with them: frames parented to the overlay being
    -- replaced would silently never draw again.
    for i = #ovLine, 1, -1 do ovLine[i] = nil end
    for i = #ovDot, 1, -1 do ovDot[i] = nil end
    for i = #ovFill, 1, -1 do ovFill[i] = nil end
    ovLineN, ovLineMax, ovDotN, ovDotMax, ovFillN, ovFillMax = 0, 0, 0, 0, 0, 0
    overlay = CreateFrame("Frame", nil, parent)
    overlay:SetFrameStrata("HIGH")
    -- Level 0, deliberately BELOW the canvas's other children. A child always
    -- draws over its own parent, so this still puts the route over the
    -- parchment -- while the map's own markers, the player arrow among them,
    -- stay on top of it. Going up instead only hid the player; matching
    -- frames by name was a guess and did not find it on this client.
    overlay:SetFrameLevel(0)
    -- Mirror the canvas EXACTLY. The shape layer -- its lines, corner nodes,
    -- glow and hover boxes -- anchors its geometry to THIS frame, while the
    -- route, its chevrons and the markers anchor to the canvas. With no
    -- points of its own the overlay's rect is degenerate, so every shape
    -- resolved its position from a center that is not the map's: drawn and
    -- counted (status said shapes=4) but parked off the parchment, which is
    -- exactly the blank map this was reported against. Same rect as the
    -- canvas makes both anchorings agree at every zoom. Mouse stays OFF: a
    -- full-canvas frame with the mouse on would swallow the map's clicks and
    -- wheel -- the hover boxes are Buttons with their own mouse and keep
    -- working regardless.
    overlay:EnableMouse(false)
    overlay:SetAllPoints(parent)
    return overlay
end

-- The pass's own bookkeeping, kept in two small functions for one hard
-- reason: a function may close over sixty outer locals, and RefreshMap
-- was over that ceiling -- the client reports it as a warning and the map
-- answers with nothing drawn. Taking the counters and their leftover
-- loops out of the pass costs it sixteen upvalues and changes no line of
-- behaviour: same pools, same order, same numbers.
local function PoolBegin()
    -- The counters start over BEFORE anything is drawn. That is the whole
    -- point of the pool: this pass takes frames 1..n, and whatever sits
    -- above n is hidden at the end of it. Resetting them anywhere else --
    -- never, most of all -- has every tick ask for FRESH frames instead of
    -- moving the ones already on screen, so each tick leaves the previous
    -- tick's chevrons and segments exactly where they were: a smear of
    -- stale route over the live one, growing eight times a second, and
    -- clearing only when the map closes.
    lineN, chevN, markN, tipN = 0, 0, 0, 0
    -- The skull belongs to the previous pass until this one says
    -- otherwise: a player who resurrects mid-run keeps no skull from the
    -- run that just ended. The corpse stroke's pool counts from zero with
    -- the rest: this pass takes textures 1..n and whatever sits above n
    -- goes down at its end.
    if mapSkull then mapSkull:Hide() end
    clLineN = 0
    M.corpseLineDrawn = nil
end

local function PoolEnd()
    -- The pass is over: drop whatever it did not take this time.
    for i = lineN + 1, lineMax do if lines[i] then lines[i]:Hide() end end
    for i = chevN + 1, chevMax do if chevs[i] then chevs[i]:Hide() end end
    for i = markN + 1, markMax do HideMarker(i) end
    for i = tipN + 1, tipMax do if tips[i] then tips[i]:Hide() end end
    lineMax, chevMax, markMax = lineN, chevN, markN
    tipMax = tipN
    for i = clLineN + 1, clLineMax do if clLine[i] then clLine[i]:Hide() end end
    clLineMax = clLineN
end

local function Line()
    lineN = lineN + 1
    local l = lines[lineN]
    if not l then
        -- Sublevel 5, the floor of the overlay: segments sit under the
        -- markers and the chevrons no matter when their pooled frame was
        -- born. Outline and line share this pool and so this sublevel; the
        -- outline is always taken first (index 1), which keeps it under.
        l = overlay:CreateTexture(nil, "OVERLAY", nil, 5)
        -- Our own line texture (128x8): an opaque core over two soft rows
        -- each side, so a stretched copy reads as a pen stroke instead of a
        -- hard rectangle -- and a fade over its first third, which makes the
        -- line grow out of the player towards the target instead of
        -- appearing all at once. (SetTexture(nil) was tried first and draws
        -- nothing at all on this client.)
        l:SetTexture("Interface\\AddOns\\" .. ADDON .. "\\Textures\\rxp-map-line.png")
        lines[lineN] = l
    end
    return l
end

-- A segment: the accent line over
-- a copy of itself darkened to 34%, not over a black bar. The dark layer is
-- what keeps the route readable: the parchment is pale along the roads and
-- near-black in the caves, and a bare accent line vanishes in one of the
-- two. Two pooled textures per segment, no table built per pass.
-- Deliberately NOT the map's "Line" frame: this client has no such template
-- -- CreateFrame("Line") answers nil and takes the whole pass down with it,
-- hundreds of warnings a session, nothing drawn.
-- `nextLine` is the pool the two textures come out of (see FlowChevrons
-- below): one drawing, two surfaces, each with its own frames.
local function DrawSegment(nextLine, parent, x1, y1, x2, y2, thick, halo, r, g, b, a)
    local dx, dy = x2 - x1, y2 - y1
    local len = math.sqrt(dx * dx + dy * dy)
    if len < 0.5 then return false end
    local ang = math.atan2(dy, dx)
    local function place(l, width, cr, cg, cb, ca)
        l:ClearAllPoints()
        l:SetPoint("CENTER", parent, "CENTER", (x1 + x2) / 2, (y1 + y2) / 2)
        l:SetWidth(len + width)
        l:SetHeight(width)
        l:SetRotation(ang)
        l:SetVertexColor(cr, cg, cb, ca)
        l:Show()
    end
    place(nextLine(), thick + halo, r * 0.34, g * 0.34, b * 0.34, a * 0.96)
    place(nextLine(), thick, r, g, b, a)
    return true
end

-- ---------------- The route as a curve ----------------
-- Straight chords between waypoints read as a zigzag: the eye follows
-- the corners instead of the road. The corners are rounded with cubic
-- Beziers that pass through EVERY waypoint: no target ever moves, only
-- the line between two of them. Each span is flattened here into three
-- to five short straight pieces, which is all the line pool draws
-- anyway; the pieces share their endpoints, so the stroke stays
-- continuous and a marker, still placed on the original waypoint,
-- still sits ON the line.
--
-- CURVE_STRENGTH is how far a handle reaches along its span, as a
-- fraction of the span's length: 0 draws the straight chords drawn
-- until now; past 0.32 the line begins to cut a corner rather than
-- rounding it. At 0.20 a corner rounds off without ever cutting one.
local CURVE_STRENGTH = 0.20
local spX, spY, spL = {}, {}, {}

-- One span -- rout[i] to rout[i+1] -- written into spX/spY: sp[1] is the
-- span's own start and sp[n] its end, both exact. Each handle points
-- from an end towards the waypoint BEYOND the span, as a unit direction
-- (a 30 px link and a 300 px link then bend in the same shape) scaled
-- by the span's own length. The first span has no waypoint before it
-- and the last has none after: those handles fall back to the span's
-- direction and come out straight, which is right -- a curve needs a
-- third point to bend towards. A handle that would point backwards off
-- a hairpin falls back the same way: without that guard a sharp turn
-- grows a hook that loops back over the route itself.
local function FlattenSpan(rout, i)
    local p1x, p1y = rout[i].x, rout[i].y
    local p2x, p2y = rout[i + 1].x, rout[i + 1].y
    local dx, dy = p2x - p1x, p2y - p1y
    local len = math.sqrt(dx * dx + dy * dy)
    if len < 1 then
        spX[1], spY[1] = p1x, p1y
        spX[2], spY[2] = p2x, p2y
        return 2
    end
    local sx, sy = dx / len, dy / len
    local t1x, t1y = sx, sy
    local prev = rout[i - 1]
    if prev then
        local ux, uy = p2x - prev.x, p2y - prev.y
        local l = math.sqrt(ux * ux + uy * uy)
        if l >= 0.001 then t1x, t1y = ux / l, uy / l end
    end
    local t2x, t2y = sx, sy
    local nxt = rout[i + 2]
    if nxt then
        local ux, uy = nxt.x - p1x, nxt.y - p1y
        local l = math.sqrt(ux * ux + uy * uy)
        if l >= 0.001 then t2x, t2y = ux / l, uy / l end
    end
    if t1x * sx + t1y * sy < 0.2 then t1x, t1y = sx, sy end
    if t2x * sx + t2y * sy < 0.2 then t2x, t2y = sx, sy end
    local h = len * CURVE_STRENGTH
    local c1x, c1y = p1x + t1x * h, p1y + t1y * h
    local c2x, c2y = p2x - t2x * h, p2y - t2y * h
    -- Three pieces on a short span, five on a long one: enough to read
    -- as one stroke, few enough that a six-link chain stays a few dozen
    -- pooled textures rather than a couple of hundred.
    local sub = (len < 70 and 3) or (len < 170 and 4) or 5
    spX[1], spY[1] = p1x, p1y
    for j = 1, sub do
        local t = j / sub
        local u = 1 - t
        local u2, u3 = u * u, u * u * u
        local t2, t3 = t * t, t * t * t
        spX[j + 1] = u3 * p1x + 3 * u2 * t * c1x + 3 * u * t2 * c2x + t3 * p2x
        spY[j + 1] = u3 * p1y + 3 * u2 * t * c1y + 3 * u * t2 * c2y + t3 * p2y
    end
    return sub + 1
end

-- The flattened span drawn piece by piece: the same stroke, the same
-- dark copy under it, the same alpha as the one straight segment it
-- replaces -- the pool does not know it is being fed a curve.
local function DrawPath(nextLine, parent, n, thick, halo, r, g, b, a)
    for i = 1, n - 1 do
        DrawSegment(nextLine, parent, spX[i], spY[i], spX[i + 1], spY[i + 1],
            thick, halo, r, g, b, a)
    end
end

-- The same flow as FlowChevrons, over the flattened span: chevrons are
-- placed by ARC LENGTH, so their spacing holds around a bend and each
-- one turns with the road under it. Density, phase and speed are the
-- straight version's -- this is that flow on a curve, not a second one.
local function FlowPathChevrons(nextChev, parent, n, size, r, g, b, a, speed, minLen)
    local total = 0
    for i = 1, n - 1 do
        local dx, dy = spX[i + 1] - spX[i], spY[i + 1] - spY[i]
        local l = math.sqrt(dx * dx + dy * dy)
        spL[i] = l
        total = total + l
    end
    if total < (minLen or 42) then return end
    local count = (total < 72) and 1 or ((total < 145) and 2 or 3)
    local phase = ((GetTime() or 0) * 0.42 * (speed or 1)) % 1
    for i = 1, count do
        -- The straight flow's own window: between a fifth and four
        -- fifths of the span, cycling with time.
        local s = total * (0.20 + ((phase + (i - 1) / count) % 1) * 0.60)
        local acc, j = 0, 1
        for k = 1, n - 1 do
            if acc + spL[k] >= s then j = k break end
            acc = acc + spL[k]
        end
        local l = spL[j]
        local t = (l > 0) and ((s - acc) / l) or 0
        if t > 1 then t = 1 end
        local x = spX[j] + (spX[j + 1] - spX[j]) * t
        local y = spY[j] + (spY[j + 1] - spY[j]) * t
        local ang = math.atan2(spY[j + 1] - spY[j], spX[j + 1] - spX[j])
        local c = nextChev()
        c:ClearAllPoints()
        c:SetPoint("CENTER", parent, "CENTER", x, y)
        c:SetWidth(size)
        c:SetHeight(size)
        c:SetRotation(ang)
        c:SetVertexColor(r, g, b, a)
        c:Show()
    end
end

-- SCAN: how far ahead the guide's path walk reads. Past a few dozen steps
-- the guide has moved on, and this runs ten times a second.
local SCAN = 40

-- ---------------- The path the guide actually walks ----------------
-- RestedXP flags EVERY #goto and #waypoint it parses with arrow=true
-- (RXPGuides/functions.lua, the goto parser): "travel through the cave
-- toward Rezlak" is a CHAIN of them, one per corner, not one point. We
-- used to take the first element with coordinates from each step and join
-- those, so the line jumped from step to step and cut over the very
-- ground the guide walks around -- the route looked nothing like the
-- guide. The walk below follows the chain in order and draws through all
-- of it; what follows is that walk.
--
-- The minimap is left alone on purpose: it draws the player, the arrow's
-- own point, then one point per following step -- which is what goes on
-- the glass here too (the per-step list is read, not the whole path).
local nodeBuf = {}        -- one step's waypoints, being gathered
local pathBuf, pathN = {}, 0     -- the whole path, in guide order

-- One of the guide's route waypoints: a navigation tag and a place on the
-- map. RestedXP's own arrow flag could be asked first, and we
-- deliberately do not: that flag is set when the line is PARSED
-- (RXPGuides/functions.lua:1884 creates every #goto with arrow=true, and
-- :1967 takes it back off when the guide writes the goto without a radius)
-- and is never touched again. On the Forever guides, where a step is
-- written as ".goto 1411/1,-4282,-250,0", the flag is nil on exactly the
-- chain waypoints the route is here to draw -- asking for it would leave
-- the line one hop per step again.
local function IsRoutePoint(e)
    if type(e) ~= "table" then return false end
    if e.skip or e.completed then return false end
    local tag = type(e.tag) == "string" and e.tag:lower() or ""
    if not (tag:find("goto", 1, true) or tag:find("waypoint", 1, true)) then
        return false
    end
    return (Spot(e) ~= nil)
end

-- Every route waypoint of a step, in the order the guide writes them,
-- starting at `startEl` when it is one of them (that is how the walk
-- continues from where the player already is). RestedXP's lowPrio
-- waypoints are left out -- they are the guide's "if you happen to be
-- passing by", not where it is going -- and two waypoints on the same spot
-- collapse into one. The step's LAST waypoint is its goal: the place the
-- step is about, where the pin belongs.
local function StepNodes(step, startEl)
    if type(step) ~= "table" or type(step.elements) ~= "table" then return 0 end
    local n = 0
    local function put(e, id, x, y)
        n = n + 1
        local b = nodeBuf[n] or {}
        b.id, b.x, b.y, b.el = id, x, y, e
        nodeBuf[n] = b
    end
    local first = 1
    if startEl then
        local found
        for i, e in ipairs(step.elements) do
            if e == startEl then first, found = i, true break end
        end
        if not found then
            -- The arrow's element belongs to another step (a transition
            -- caught mid-settle): it is still the point we are sent to.
            local id, x, y = Spot(startEl)
            if id then put(startEl, id, x, y) end
            return n
        end
    end
    local lastId, lastX, lastY
    for i = first, #step.elements do
        local e = step.elements[i]
        if IsRoutePoint(e) and (e == startEl or not e.lowPrio) then
            local id, x, y = Spot(e)
            if not (id == lastId and math.abs(x - lastX) < 0.00005
                    and math.abs(y - lastY) < 0.00005) then
                put(e, id, x, y)
                lastId, lastX, lastY = id, x, y
            end
        end
    end
    return n
end

-- The whole path the world map draws: the step being walked, from the
-- arrow's own element through every waypoint of its chain at full
-- opacity, then the steps after it up to the quota, each one's chain, each
-- one dimmer than the last. Fills pathBuf and answers how many waypoints
-- it holds; the alpha of each is set here so the drawing pass never has to
-- know how many steps the fade spans.
local function RoutePath(want, chainA)
    pathN, M.routeNodes, M.routeSteps = 0, nil, nil
    local RXP = ns.GetRXP()
    local guide = RXP and RXP.currentGuide
    local steps = guide and guide.steps
    if not (steps and #steps > 0) then return 0 end
    local at = ActiveIndex()
    if not at then return 0 end
    want = math.max(0, tonumber(want) or 0)

    local function append(s, stepIndex, ord, first)
        pathN = pathN + 1
        local p = pathBuf[pathN] or {}
        p.id, p.x, p.y, p.el, p.step = s.id, s.x, s.y, s.el, stepIndex
        p.ord, p.first = ord, first
        pathBuf[pathN] = p
        return p
    end
    -- A step with no waypoint chain at all -- an item, a quest, a mob with
    -- no fixed place -- still has an objective: its own leading element
    -- stands in, which is the fallback taken here.
    local function nodesOrObjective(step, startEl)
        local n = StepNodes(step, startEl)
        if n > 0 then return n end
        local e = PickStepElement(step)
        local id, x, y = Spot(e)
        if not id then return 0 end
        nodeBuf[1] = { id = id, x = x, y = y, el = e }
        return 1
    end

    local n = nodesOrObjective(steps[at], CurrentElement())
    for k = 1, n do
        append(nodeBuf[k], at, 0, true).goal = (k == n)
    end
    if pathN == 0 then
        -- Nothing in the step resolved: the arrow's own point is the route.
        local id, x, y = CurrentSpot()
        if not id then return 0 end
        nodeBuf[1] = { id = id, x = x, y = y, el = CurrentElement() }
        append(nodeBuf[1], at, 0, true).goal = true
    end

    local found = 0
    local si = at + 1
    local last = math.min(#steps, at + SCAN)
    while si <= last and found < want do
        local step = steps[si]
        -- A #loop step never joins the line: it is ground to work over,
        -- not a waypoint to walk, and the overlay pass draws it.
        if step and not step.skip and not step.completed and not step.loop
            and type(step.elements) == "table" then
            local m = nodesOrObjective(step, nil)
            if m > 0 then
                found = found + 1
                for k = 1, m do
                    append(nodeBuf[k], si, found, false).goal = (k == m)
                end
            end
        end
        si = si + 1
    end

    -- The fade spans the steps actually FOUND, not the ones asked for: the
    -- first at Chain Visibility, the last at half of it, every waypoint of
    -- a step at its own step's alpha.
    for k = 1, pathN do
        local p = pathBuf[k]
        if p.ord == 0 then
            p.a = 1
        else
            p.a = chainA * (1 - 0.5 * ((p.ord - 1) / math.max(1, found - 1)))
        end
    end
    M.routeNodes, M.routeSteps = pathN, found
    return pathN
end

-- ---------------- The overlay layer on the world map ----------------
-- One texture off the pool, sublevel 2: OVER the fill below it (1) and
-- UNDER the route's floor (5), so shapes and bearing never fight.
local function OverlayLine()
    ovLineN = ovLineN + 1
    local l = ovLine[ovLineN]
    if not l then
        l = overlay:CreateTexture(nil, "OVERLAY", nil, 2)
        -- DrawSegment PLACES and TINTS this texture, it never sets its
        -- picture -- the pool maker has to, once, at birth (the route's
        -- own Line() does exactly this). Without this call the whole layer
        -- paints invisible lines: shapes counted, pixels zero, which is
        -- precisely what the first release shipped.
        l:SetTexture("Interface\\AddOns\\" .. ADDON .. "\\Textures\\rxp-map-line.png")
        ovLine[ovLineN] = l
    end
    return l
end

-- What kind of shape an element describes, in the words the guide puts on
-- it (checked in a fixed order: the guide's own verb first, the
-- generic nouns after -- "patrol" beats "area", "farm" beats "path"). An
-- element with no sentence a classifier recognises draws nothing rather
-- than something invented.
local function OverlayKind(el)
    if type(el) ~= "table" or el.skip or el.completed then return nil end
    if type(el.segments) ~= "table" or #el.segments < 4 then return nil end
    local t = tostring(el.text or el.title or ""):lower()
    if t:find("patrol", 1, true) or t:find("roam", 1, true) or t:find("wander", 1, true) then
        return "patrol"
    end
    if t:find("farm", 1, true) or t:find("grind", 1, true)
        or t:find("loop", 1, true) or t:find("circuit", 1, true) then
        return "farm"
    end
    if tonumber(el.range) ~= nil or t:find("search", 1, true) or t:find("area", 1, true) then
        return "search"
    end
    if t:find("path", 1, true) or t:find("route", 1, true) then return "farm" end
    return nil
end

-- The kind of GROUND a #loop step is, read off the words the guide puts on
-- it. The classifier's own words come first -- a loop that says patrol IS one.
-- After that, what the Forever guides actually write, because their 362
-- circuits never say "patrol": they say "Kill X", "Loot Y", "Grind to
-- level N", "Use Z on W". So the kind is told by the verb, in this order:
-- KILL BEFORE LOOT, since "Kill Kul Tiras Sailors and Marines. Loot them
-- for their Canvas Scraps" is a kill circuit that mentions looting -- and
-- with it the ground gets a pen of its own instead of everything mint.
local function LoopKind(step)
    if type(step) ~= "table" or type(step.elements) ~= "table" then return nil end
    local text = ""
    for i = 1, #step.elements do
        local e = step.elements[i]
        if type(e) == "table" and not e.skip and not e.completed then
            local t = e.text
            if type(t) ~= "string" then t = e.title end
            if type(t) == "string" and t ~= "" then text = text .. " " .. t end
        end
    end
    text = text:lower()
    if text:find("patrol", 1, true) or text:find("roam", 1, true)
        or text:find("wander", 1, true) then
        return "patrol"
    end
    if text:find("kill", 1, true) or text:find("grind", 1, true)
        or text:find("hunt", 1, true) then
        return "farm"
    end
    if text:find("loot", 1, true) or text:find("collect", 1, true)
        or text:find("gather", 1, true) or text:find("pick up", 1, true) then
        return "search"
    end
    if text:find("talk", 1, true) or text:find("use ", 1, true)
        or text:find("interact", 1, true) or text:find("activate", 1, true) then
        return "interact"
    end
    return "farm"
end

-- Which switch a loop answers to, and which pen draws it: four kinds read
-- from the guide's sentence, three pens. An interact loop shares the amber
-- of a patrol -- both are ground you walk from point to point, not ground
-- you comb -- while the label the tooltip prints stays its own.
local OV_LOOP_STYLE = {
    farm = "farm",
    search = "search",
    patrol = "patrol",
    interact = "patrol",
}

-- The element's own coordinates -- zone percentages, exactly as the guide
-- wrote them -- projected onto the displayed map and into canvas pixels by
-- the same two calls the route's markers go through, so a shape and the
-- route above it can never disagree about where the ground is.
local function OverlayProject(el, displayID, w, h)
    local zone = tonumber(el.zone)
    if not zone or IsSecret(zone) then return 0 end
    local n = 0
    for i = 1, #el.segments, 2 do
        local sx, sy = tonumber(el.segments[i]), tonumber(el.segments[i + 1])
        local x, y = sx and sx / 100, sy and sy / 100
        if x and y and x >= 0 and x <= 1 and y >= 0 and y <= 1
            and not IsSecret(x) and not IsSecret(y) then
            local rx, ry = ReProject(zone, x, y, displayID)
            if rx and ry then
                n = n + 1
                local p = ovPts[n] or {}
                p.x, p.y = Cx(rx, w), Cy(ry, h)
                ovPts[n] = p
            end
        end
    end
    return n
end

-- The shape's own rectangle on the canvas: the hover target of the shape
-- and, for a search area, the box its glow is laid over. One pass over
-- the points, two answers.
local function OvBounds(n)
    local minX, maxX, minY, maxY = ovPts[1].x, ovPts[1].x, ovPts[1].y, ovPts[1].y
    for i = 2, n do
        local p = ovPts[i]
        if p.x < minX then minX = p.x end
        if p.x > maxX then maxX = p.x end
        if p.y < minY then minY = p.y end
        if p.y > maxY then maxY = p.y end
    end
    return minX, maxX, minY, maxY
end

-- One hover target per drawn shape, sized to the shape's own box and drawn
-- as nothing at all: the point is not to write the mob's name on the map
-- -- that would be a label over every circuit in the zone -- but to answer
-- the mouse. It rides the same switches as the markers' tooltip and reads
-- the same fields, so what comes out is the guide's own words: which step
-- the ground belongs to, that step's title, and the lines telling the
-- player what to do there. The strata is TOOLTIP, like theirs, so the
-- map's own pins cannot swallow the hover.
local function OvTip(parent, kind, n, el, stepNo, map)
    if not TipShow("rxpTipOn") or not el then return end
    local minX, maxX, minY, maxY = OvBounds(n)
    local cx, cy = (minX + maxX) / 2, (minY + maxY) / 2
    ovTipN = ovTipN + 1
    local t = ovTips[ovTipN]
    if not t then
        t = CreateFrame("Button", nil, overlay)
        t:EnableMouse(true)
        t:SetFrameStrata("TOOLTIP")
        t:SetFrameLevel(1)
        t:SetScript("OnEnter", TipEnter)
        t:SetScript("OnLeave", TipHide)
        t:SetScript("OnHide", TipHide)
        ovTips[ovTipN] = t
    end
    t:ClearAllPoints()
    t:SetPoint("CENTER", parent, "CENTER", cx, cy)
    t:SetSize(math.max(24, maxX - minX), math.max(24, maxY - minY))
    -- Same compass contract as a marker: read back out of the canvas
    -- coordinates the shape was drawn from.
    local w, h = parent:GetWidth(), parent:GetHeight()
    if w and h and w > 0 and h > 0 then
        t.mx, t.my = (cx + w / 2) / w, (h / 2 - cy) / h
    else
        t.mx, t.my = nil, nil
    end
    t.el, t.step, t.ordinal, t.map, t.cum = el, stepNo, nil, map, nil
    t.kind = kind
    t:Show()
end

-- One shape drawn, straight or dashed, over the points in ovPts: the same
-- pen stroke as the route (our line texture over its own 34% dark copy),
-- so the layer reads as this addon's and not as something pasted in. A
-- patrol is cut into 14 px dashes with 9 px gaps -- the rhythm that says
-- "something walks here" rather than "walk this way". `close` joins the
-- last point back to the first (circuits); `anyInside` draws a span only
-- when at least one of its ends is on the glass -- the minimap passes it,
-- so a shape entirely off the rim leaves no arc drawn along the rim.
local function DrawOverlayShape(nextLine, parent, kind, n, thick, r, g, b, a, close, anyInside)
    local last = close and n or (n - 1)
    local dash = (kind == "patrol")
    for i = 1, last do
        local p1 = ovPts[i]
        local p2 = ovPts[(i % n) + 1]
        if p1 and p2 and (not anyInside or p1.inside or p2.inside) then
            local x1, y1, x2, y2 = p1.x, p1.y, p2.x, p2.y
            local halo = thick * 0.6
            if not dash then
                DrawSegment(nextLine, parent, x1, y1, x2, y2, thick, halo, r, g, b, a)
            else
                local dx, dy = x2 - x1, y2 - y1
                local len = math.sqrt(dx * dx + dy * dy)
                if len >= 1 then
                    local ux, uy = dx / len, dy / len
                    local pos = 0
                    while pos < len do
                        local stop = math.min(len, pos + 14)
                        if stop - pos >= 1 then
                            DrawSegment(nextLine, parent,
                                x1 + ux * pos, y1 + uy * pos,
                                x1 + ux * stop, y1 + uy * stop,
                                thick, halo, r, g, b, a)
                        end
                        pos = pos + 14 + 9
                    end
                end
            end
        end
    end
end

-- Where the first drawn shape sits, as a line /euirxp status can print:
-- kind, point count, and the shape's centre in 0..1 map coordinates. Two
-- decimals are the difference between "drawn out of view" and "not drawn
-- at all", which pixels alone cannot say through a chat window.
local function OverlaySample(kind, n, w, h)
    if n < 1 or not (w and h and w > 0 and h > 0) then return nil end
    local minX, maxX, minY, maxY = ovPts[1].x, ovPts[1].x, ovPts[1].y, ovPts[1].y
    for i = 2, n do
        local p = ovPts[i]
        if p.x < minX then minX = p.x end
        if p.x > maxX then maxX = p.x end
        if p.y < minY then minY = p.y end
        if p.y > maxY then maxY = p.y end
    end
    local cx, cy = (minX + maxX) / 2, (minY + maxY) / 2
    return string.format("%s %dpts %.2f/%.2f", kind, n,
        (cx / w) + 0.5, 0.5 - (cy / h))
end

-- One pass over the shape layer, run by RefreshMap with everything it
-- needs already measured: the guide's current step, then as many steps
-- ahead as Upcoming Markers asks for (the same quota the chain draws),
-- each shape classified, projected and drawn in its own colour at the one
-- Overlay opacity. A #loop step whose circuit lives in its gotos instead
-- of a single segments list is drawn from THOSE -- closed, mint -- but
-- never both: a step gets one shape, not two on top of each other.
local function OverlayDraw(db, displayID, w, h, boost)
    if not OverlayWanted(db) then
        OverlayRelease()
        return
    end
    ovLineN, ovDotN, ovFillN, ovTipN = 0, 0, 0, 0
    local alpha = tonumber(db.rxpOverlayAlpha) or 0.8
    if alpha < 0.2 then alpha = 0.2 elseif alpha > 1 then alpha = 1 end
    local thick = math.max(1.8, 2.1 * (boost or 1))
    local on = {
        farm = not not db.rxpOverlayFarm,
        patrol = not not db.rxpOverlayPatrol,
        search = not not db.rxpOverlaySearch,
    }
    local RXP = ns.GetRXP()
    local guide = RXP and RXP.currentGuide
    local steps = guide and guide.steps
    local at = (steps and #steps > 0) and ActiveIndex() or nil
    if not at then
        M.overlayDrawn = 0
        M.overlayWhy = "no active step"
        return
    end
    local future = tonumber(db.rxpMapFuture) or 0
    if future < 0 then future = 0 end
    local drawn, futureShapes = 0, 0
    -- WHY nothing, counted at each gate: a step can hold a shape and still
    -- not reach the map (off this zone), reach it but be switched off, or
    -- hold no shape at all -- and "no farm route visible" reads the same
    -- for all three until someone counts them.
    local noKind, noOff, noMap, noLoop = 0, 0, 0, 0
    -- The quota counts SHAPES, not steps -- the same rule the chain of
    -- markers follows: most steps carry no shape at all, so stopping after
    -- six steps would draw none while Upcoming Markers reads 6. The scan
    -- walks past empty steps until it has filled the quota (40 steps deep,
    -- the chain's own reach).
    local si = at
    local limit = math.min(#steps, at + 39)
    while si <= limit do
        if si > at and futureShapes >= future then break end
        local step = steps[si]
        if step and not step.skip and not step.completed and type(step.elements) == "table" then
            local before = drawn
            local anyShape = false
            for i = 1, #step.elements do
                local el = step.elements[i]
                local kind = OverlayKind(el)
                if not kind then noKind = noKind + 1 end
                if kind and not on[kind] then noOff = noOff + 1 end
                if kind and on[kind] then
                    local n = OverlayProject(el, displayID, w, h)
                    if n < 2 then noMap = noMap + 1 end
                    if n >= 2 then
                        local cr, cg, cb, ca = OVColor(db, kind)
                        DrawOverlayShape(OverlayLine, overlay, kind, n,
                            thick, cr, cg, cb, alpha * (ca or 1), true)
                        OvTip(overlay, kind, n, el, si, MapID(el))
                        if kind == "farm" then
                            -- A node on each corner: what turns a mint blob
                            -- into a circuit with stops. Seven pixels, the
                            -- guide's own dot, a whisker brighter than the
                            -- line so the corners read through it.
                            for k = 1, n do
                                ovDotN = ovDotN + 1
                                local dot = ovDot[ovDotN]
                                if not dot then
                                    dot = overlay:CreateTexture(nil, "OVERLAY", nil, 3)
                                    dot:SetTexture("Interface\\AddOns\\" .. ADDON
                                        .. "\\Textures\\rxp-map-center.png")
                                    ovDot[ovDotN] = dot
                                end
                                dot:ClearAllPoints()
                                dot:SetPoint("CENTER", overlay, "CENTER",
                                    ovPts[k].x, ovPts[k].y)
                                dot:SetSize(7, 7)
                                dot:SetVertexColor(cr, cg, cb, math.min(1, alpha + 0.08) * (ca or 1))
                                dot:Show()
                            end
                        elseif kind == "search" then
                            -- The area itself: a soft glow over the shape's
                            -- bounding box -- 42 px floor so a point-sized
                            -- area still reads as ground, 20% growth so the
                            -- contour sits inside the light. Fill stays
                            -- under half opacity: the map must stay readable.
                            local minX, maxX, minY, maxY = OvBounds(n)
                            ovFillN = ovFillN + 1
                            local fill = ovFill[ovFillN]
                            if not fill then
                                fill = overlay:CreateTexture(nil, "BACKGROUND", nil, 1)
                                ovFill[ovFillN] = fill
                            end
                            fill:SetTexture("Interface\\AddOns\\" .. ADDON
                                .. "\\Textures\\rxp-map-glow.png")
                            fill:SetBlendMode("ADD")
                            fill:ClearAllPoints()
                            fill:SetPoint("CENTER", overlay, "CENTER",
                                (minX + maxX) / 2, (minY + maxY) / 2)
                            fill:SetSize(math.max(42, (maxX - minX) * 1.2),
                                math.max(42, (maxY - minY) * 1.2))
                            fill:SetVertexColor(cr, cg, cb, math.max(0.05, math.min(0.55, alpha * 0.4)) * (ca or 1))
                            fill:Show()
                        end
                        drawn = drawn + 1
                        if not M.overlaySample then
                            M.overlaySample = OverlaySample(kind, n, w, h)
                        end
                        anyShape = true
                    end
                end
            end
            -- The circuit written as gotos: a closed mint polyline, but
            -- only when the step carries no segments of its own -- drawing
            -- both would lay the same ground twice.
            local lkind = (step.loop and not anyShape) and LoopKind(step) or nil
            local lstyle = lkind and OV_LOOP_STYLE[lkind] or nil
            if lstyle and on[lstyle] then
                local n, tipEl, tipMap = 0, nil, nil
                for i = 1, #step.elements do
                    local el = step.elements[i]
                    if type(el) == "table" and not el.skip and not el.completed then
                        local tag = type(el.tag) == "string" and el.tag:lower() or ""
                        if tag:find("goto", 1, true) then
                            local id, x, y = Spot(el)
                            if id then
                                local rx, ry = ReProject(id, x, y, displayID)
                                if rx and ry then
                                    n = n + 1
                                    if n == 1 then tipEl, tipMap = el, id end
                                    local p = ovPts[n] or {}
                                    p.x, p.y = Cx(rx, w), Cy(ry, h)
                                    ovPts[n] = p
                                end
                            end
                        end
                    end
                end
                if n >= 3 then
                    local cr, cg, cb, ca = OVColor(db, lstyle)
                    DrawOverlayShape(OverlayLine, overlay, lstyle, n,
                        thick, cr, cg, cb, alpha * (ca or 1), true)
                    OvTip(overlay, lkind, n, tipEl, si, tipMap)
                    drawn = drawn + 1
                    if not M.overlaySample then
                        M.overlaySample = OverlaySample(lkind, n, w, h)
                    end
                elseif n > 0 then
                    noLoop = noLoop + 1
                end
            end
            if si > at then futureShapes = futureShapes + (drawn - before) end
        end
        si = si + 1
    end
    -- Leftovers, the route's way: hide what this pass did not take.
    for i = ovLineN + 1, ovLineMax do if ovLine[i] then ovLine[i]:Hide() end end
    for i = ovDotN + 1, ovDotMax do if ovDot[i] then ovDot[i]:Hide() end end
    for i = ovFillN + 1, ovFillMax do if ovFill[i] then ovFill[i]:Hide() end end
    for i = ovTipN + 1, ovTipMax do if ovTips[i] then ovTips[i]:Hide() end end
    ovLineMax, ovDotMax, ovFillMax = ovLineN, ovDotN, ovFillN
    ovTipMax = ovTipN
    M.overlayDrawn = drawn
    -- The one-line answer to "where are the farm routes", in the guide's
    -- own numbers rather than in guesswork.
    M.overlayWhy = drawn > 0 and "drawn"
        or (noMap > 0 and ("off this map (" .. noMap .. ")")
            or (noOff > 0 and ("switch off (" .. noOff .. ")")
                or ((noKind + noLoop) > 0
                    and ("no shape in the next steps (" .. (noKind + noLoop) .. ")")
                    or "nothing to draw here")))
end

-- One pass: draw what the guide and the player currently justify, then drop
-- whatever this pass did not take (a target the guide moved away from).
-- Called on a timer while the map is open, and directly on a settings or
-- accent change.
function M.RefreshMap()
    local db = DB()
    if not (db and db.rxpMapRoute) then
        Release()
        return
    end
    local wm = _G.WorldMapFrame
    if not (wm and wm.IsShown and wm:IsShown()) then
        Release()
        return
    end
    local displayID = DisplayMapID()
    if not displayID then
        Release()
        return
    end
    -- The target is the BODY'S while the player is a ghost -- the corpse
    -- outranks the guide, since a step cannot be walked to from beyond
    -- the veil -- and the guide's otherwise. Missing both does not
    -- end the pass any more: the shapes at the end need no target, and
    -- "no target" is RestedXP's normal state between two steps, so this
    -- exit used to take the farm circuits down with a route they never
    -- depended on. The reason is kept and printed instead.
    -- The body takes priority over the guide while the player is a
    -- ghost: a step's target cannot be walked to from beyond the veil,
    -- and the corpse gets the arrow first for exactly
    -- that reason. Alive, CorpseSpot costs one boolean and answers nil.
    local corpseMap, cRawX, cRawY = CorpseSpot()
    local corpse = corpseMap ~= nil
    local targetID, rawX, rawY
    if corpse then
        targetID, rawX, rawY = corpseMap, cRawX, cRawY
    else
        targetID, rawX, rawY = CurrentSpot()
    end
    local noRoute
    local tx, ty
    if not targetID then
        noRoute = "no target yet"
    else
        tx, ty = ReProject(targetID, rawX, rawY, displayID)
        if not tx then
            noRoute = "target off this map"
        end
    end
    local px, py = PlayerSpot(displayID)
    if not (px and py) and corpse then
        -- While ghosted the client can withold the position on the map
        -- being read; the anchor remembers where the player last answered
        -- from, and that point comes onto THIS map like any other.
        local amap, ax, ay = PlayerAnchor()
        if amap and ax and ay then px, py = ReProject(amap, ax, ay, displayID) end
    end
    if not (px and py) and not noRoute then
        noRoute = "no player position"
    end
    local canvas = Canvas()
    if not canvas then
        Release()
        return
    end
    local w, h = canvas:GetWidth(), canvas:GetHeight()
    if not (w and h and w > 0 and h > 0) then
        Release()
        return
    end
    -- From here the pass commits: this is the map every marker of this
    -- pass is being placed on, and the one the tooltip's compass and
    -- distance will be read against.
    drawnMap = displayID

    EnsureOverlay(canvas)
    if overlay:GetParent() ~= canvas then
        Release()
        return
    end
    overlay:Show()

    -- The per-pass counters start over HERE, before anything is drawn --
    -- the whole point of the pool (PoolBegin below carries the rule and
    -- the counters themselves: this pass may not reach sixty outer
    -- locals, and naming them here is what took it over).
    PoolBegin()

    if noRoute then
        -- No goal this tick: Release takes the route pools down (their
        -- reason stays in the status line) -- route, stroke and skull
        -- together, so a tick with no target leaves no stale red line
        -- behind -- while the shapes keep their pass: one refresh owns
        -- both layers, and an exit that took the route down used to take
        -- the shapes with it. During a corpse run the guide is not being
        -- walked, so its shapes come down too (Release already did it):
        -- the map owes the run back to the body and nothing else.
        Release()
        M.routeState = noRoute
        if not corpse then
            OverlayDraw(db, displayID, w, h, ThicknessBoost(displayID))
        end
        return
    end

    -- The color source: the Theme page, not the raw accent. ThemeAccent()
    -- answers the custom color when "Follow Accent" is off and the live
    -- accent when it is on -- the same rule the RXP theme, the classic reskin
    -- and the arrow tint already follow, so the map route cannot disagree with
    -- the rest of the suite. GetAccentColor() ignores the custom color, which
    -- is why the route came out in the wrong green on a personalized page.
    local r, g, b
    if corpse then
        -- Blood red, the run's own colour: the Theme accent belongs to
        -- the guide's route, and a ghost is not walking the guide.
        r, g, b = CORPSE_LINE[1], CORPSE_LINE[2], CORPSE_LINE[3]
    else
        r, g, b = ns.ThemeAccent()
    end
    local ex, ey = Cx(tx, w), Cy(ty, h)
    local boost = ThicknessBoost(displayID)

    -- The bearing to the current target, in the Theme page's color. The
    -- measurements: ~3 px of line (the "thin" style, 3.0 * 0.74) over a
    -- dark 34% copy of itself, 11-16 px chevrons, a 14 px marker the zoom
    -- shrinks -- all driven by one boost so zooming keeps the proportions.
    -- One weight, one slider: Line Thickness on the Map page multiplies
    -- the stroke AND its dark outline, here and on the minimap alike, so
    -- the two surfaces cannot drift apart. 1.00 is the route exactly as it
    -- ships, and the zoom boost still rides on top.
    local weight = db.rxpMapThickness or 1
    local thick = math.max(2.6, 2.22 * boost) * weight
    local halo = math.max(1.6, boost) * weight
    local chevSize = math.min(16, 11 + (boost - 1) * 1.8)
    local flowSpeed = db.rxpMapFlowSpeed or 0.5

    -- Then the next steps, chained from the target. They are brought into
    -- the displayed map the same way: a step on another map of the same
    -- continent is reprojected and drawn, and only a map with no shared
    -- continent is left out -- the chain then continues from the last step
    -- that did land here. Steps sharing a spot collapse into one marker,
    -- the way RestedXP's own markers do.
    -- Projected BEFORE anything is drawn: the curve below bends every span
    -- towards the waypoint beyond it, so even the bearing's own shape
    -- depends on where the first chain link sits.
    -- A corpse run owes no chain: the body is the only goal, and the
    -- guide's upcoming steps are not going anywhere until it is walked
    -- back to (corpse mode drops its future overlays for the same
    -- reason).
    local want = corpse and 0 or (db.rxpMapFuture or 0)
    local chainA = db.rxpMapChainAlpha or 0.55
    -- The guide's own path, walked in order: the arrow's element and every
    -- waypoint of the step being walked, then the chain of each following
    -- step up to the quota. Gathered and projected BEFORE the first frame
    -- is taken from the pool -- the curve bends every span towards the
    -- waypoint beyond it, so even the first line's own shape depends on
    -- where the rest of the path sits.
    local np
    if corpse then
        -- The body is the one point of this pass: no guide chain, no
        -- guide steps -- the line below runs straight from the player to
        -- it. The counters still answer the status in the status's own
        -- units: one point, no step behind it.
        np = 0
        M.routeNodes, M.routeSteps = 1, 0
    else
        np = RoutePath(want, chainA)
    end

    -- Pass 1, before a single frame is taken from the pool: bring every
    -- waypoint of the path onto the map this pass is drawing, in guide
    -- order. A waypoint whose map shares no continent with this one has no
    -- place here and is left out; two waypoints landing on the same pixel
    -- collapse into one, so a step that repeats a spot does not stack.
    local pts, pn = ptsBuf, 0
    for o = 1, want do goalIdx[o] = nil end
    local prevX, prevY
    for i = 1, np do
        local p = pathBuf[i]
        local fx, fy = ReProject(p.id, p.x, p.y, displayID)
        if fx and fy then
            local cx, cy = Cx(fx, w), Cy(fy, h)
            if pn == 0 or math.abs(cx - prevX) > 0.5 or math.abs(cy - prevY) > 0.5 then
                pn = pn + 1
                local q = pts[pn] or {}
                q.x, q.y, q.nx, q.ny = cx, cy, fx, fy
                q.a, q.first, q.goal, q.ord = p.a, p.first, p.goal, p.ord
                q.el, q.step, q.map = p.el, p.step, p.id
                pts[pn] = q
                if q.ord > 0 then goalIdx[q.ord] = pn end
                prevX, prevY = cx, cy
            end
        end
    end
    if corpse then
        -- The body itself is the one waypoint: one full-opacity span
        -- from the player out to it, the chevrons on that span, the
        -- marker over it -- and the words the hover reads are the run's
        -- own, not the guide's, because no guide step is being walked.
        pn = 1
        local q = pts[1] or {}
        q.x, q.y, q.nx, q.ny = Cx(tx, w), Cy(ty, h), tx, ty
        q.a, q.first, q.goal, q.ord = 1, true, true, 0
        q.el, q.step, q.map = CorpseElement(), nil, targetID
        pts[1] = q
    end
    -- The pin of the step being walked stands on that step's OWN goal --
    -- the last waypoint of its chain, the place the step is about. The
    -- arrow's element is the first corner of that walk, not its end, and
    -- it already opens the line below.
    local gx, gy, gel, gmap = ex, ey, CurrentElement(), targetID
    local gnx, gny = tx, ty
    for i = pn, 1, -1 do
        local q = pts[i]
        if q.first then
            gx, gy, gel, gmap = q.x, q.y, q.el, q.map
            gnx, gny = q.nx, q.ny
            break
        end
    end
    -- The chain's LINKS, one per following step, on that step's goal: the
    -- clustering is unchanged (two steps standing on one spot are one
    -- marker and one link, not two), up to the quota. Knowing the final
    -- count first is what lets the fade span FIRST..LAST: two markers and
    -- six markers both start at Chain Visibility and end at half of it.
    local links, ln = chainBuf, 0
    local hx, hy = tx, ty
    local folded, offMap = 0, 0
    -- Only the steps RoutePath actually collected: a step the scan never
    -- reached is "nothing behind us", not "somewhere off this map".
    for o = 1, math.min(want, M.routeSteps or want) do
        local gi = goalIdx[o]
        local q = gi and pts[gi] or nil
        if q then
            if ln >= want then break end
            if math.abs(hx - q.nx) < CLUSTER and math.abs(hy - q.ny) < CLUSTER then
                hx, hy = q.nx, q.ny   -- same place: extend the chain, no link
                folded = folded + 1
            else
                ln = ln + 1
                local e = links[ln] or {}
                e.x, e.y = q.x, q.y
                -- The SAME point in the map's own 0..1 space, kept beside
                -- the canvas pixels: the world-distance pass below measures
                -- legs through MapWorldPos, which reads NORMALIZED coords --
                -- feeding it the pixels drew world positions hundreds of
                -- map-widths outside the zone, and the running total came
                -- back in the thousands of kilometres (1046.5 km to walk
                -- across Dun Morogh).
                e.nx, e.ny = q.nx, q.ny
                -- What the hover tooltip will need: the element, the
                -- guide step it came from, and the map it lives on.
                e.el, e.step, e.map = q.el, q.step, q.map
                links[ln] = e
                hx, hy = q.nx, q.ny
            end
        else
            -- A step whose every waypoint belongs to a zone the displayed
            -- map cannot show (another continent: the conversion answers
            -- nil rather than a position). Those are dropped; what
            -- it must not do is drop them SILENTLY, which is what left a
            -- short chain unexplained.
            offMap = offMap + 1
        end
    end

    -- The polyline the curve reads: the player, then every waypoint of the
    -- path in order. One slot past the end is dropped so the LAST span
    -- never takes its handle from a waypoint a longer path left there in
    -- an earlier pass.
    RoutePoint(1, Cx(px, w), Cy(py, h))
    for k = 1, pn do
        RoutePoint(k + 1, pts[k].x, pts[k].y)
    end
    routBuf[pn + 2] = nil

    -- One span per segment, each at its own step's alpha: full opacity
    -- through the step the player is walking -- the arrow's element and
    -- every waypoint of its chain -- then the fade over the steps after it.
    -- A first waypoint standing on the player drops its own span only (four
    -- pixels of line is not a route); the rest of the path is still going
    -- somewhere.
    local skipFirst = pn > 0 and math.abs(px - pts[1].nx) < MIN_SPAN
        and math.abs(py - pts[1].ny) < MIN_SPAN
    for k = 1, pn do
        local q = pts[k]
        if not (skipFirst and k == 1) then
            local wt, ml = thick, nil
            if not q.first then
                wt, ml = thick * 0.92, 24
            end
            local sn = FlattenSpan(routBuf, k)
            if corpse then
                -- The stroke comes out of ITS OWN pool, hosted on the
                -- route frame hung on the back of the canvas: it runs the
                -- whole way to the icons and slides UNDER them -- above
                -- the map's background, below the icons the map draws
                -- over it -- no gap anywhere. The count of strokes goes
                -- with the pool itself.
                DrawPath(CLine, canvas, sn, wt, halo, r, g, b, q.a)
                -- The skull instead of the chevrons, ONE of it, riding
                -- the span the curve just flattened.
                CorpseSkull(MapSkull(), canvas,
                    routBuf[1].x, routBuf[1].y,
                    routBuf[pn + 1].x, routBuf[pn + 1].y, 14, flowSpeed)
            else
                DrawPath(Line, canvas, sn, wt, halo, r, g, b, q.a)
                -- The chevron stays WHITE, whatever the theme says: it sits on top of
                -- the line, and tinting it with the same color buried it in its own
                -- segment -- white is the colour that survives every line.
                FlowPathChevrons(Chevron, canvas, sn, chevSize, 1, 1, 1, q.a, flowSpeed, ml)
            end
        end
    end
    local msize = MarkerSize(boost)
    -- The centre dot marks the step the player is ON; the chain below is
    -- rings only, which is what keeps it light. NOT on a corpse run: the
    -- game already puts its own tombstone over the body, and a bullseye
    -- over a tombstone is two icons arguing over one place.
    if not corpse then
        Marker(canvas, gx, gy, msize, r, g, b, 1, true)
    end
    -- The running distance the hover tooltips report: this marker's own
    -- way from the player, then every chain link measured from the one
    -- before it -- so a marker three steps ahead shows the whole route to
    -- it, and the time to walk it, instead of a hop from a point the
    -- player has not reached yet. Both ends are positions on the map this
    -- pass is drawing, the same ones the marker was placed at.
    local pwx, pwy = MapWorldPos(displayID, px, py)
    local prevWX, prevWY = MapWorldPos(displayID, gnx, gny)
    local run = WorldDist(pwx, pwy, prevWX, prevWY)
    -- What stands under the cursor: the element the marker was drawn from
    -- (arrow element or current step), so the tooltip shows the same target
    -- RestedXP's own arrow is heading for. While the tooltip switch is off
    -- no button is built at all: a marker that catches the mouse without
    -- saying anything would only be a hole in the map.
    if TipShow("rxpTipOn") then
        Tip(canvas, gx, gy, msize, gel, nil, 1, gmap, run)
    end

    -- Pass 2: draw the chain, each link dimmer than the one before it --
    -- Chain Visibility on the first, half of it on the last, spread over
    -- however many links pass 1 found. The segment, its chevrons and the
    -- marker it points at all take that same alpha, so a link reads as one
    -- thing instead of three different greys.
    for k = 1, ln do
        local t = (k - 1) / math.max(1, ln - 1)
        local a = chainA * (1 - 0.5 * t)
        local sx, sy = links[k].x, links[k].y
        -- The line through these waypoints was drawn with the rest of the
        -- path above; what is left for a link is its marker and its number.
        -- The rule: future markers keep the target's exact size and
        -- are told apart by opacity alone -- and by the missing centre:
        -- only the step the player is on wears the dot.
        Marker(canvas, sx, sy, MarkerSize(boost), r, g, b, a, false)
        -- One more leg on the running total -- measured between the two
        -- NORMALIZED positions (the link's nx/ny, not its canvas pixels:
        -- MapWorldPos reads the map's 0..1 space, and pixels in it meant
        -- legs hundreds of times too long). Once a leg cannot be measured
        -- the total stops there and every later marker falls back to its
        -- own straight line: a missing number beats a wrong one.
        local cwx, cwy = MapWorldPos(displayID, links[k].nx, links[k].ny)
        if run then
            local seg = WorldDist(prevWX, prevWY, cwx, cwy)
            run = seg and (run + seg) or nil
        end
        prevWX, prevWY = cwx, cwy
        if TipShow("rxpTipOn") then
            Tip(canvas, sx, sy, MarkerSize(boost), links[k].el, links[k].step,
                k + 1, links[k].map, run)
        end
    end

    -- Markers asked for and markers drawn, so /euirxp status can answer
    -- "why fewer than I asked for?" without anyone counting pixels.
    M.chainWanted, M.chainDrawn = want, ln
    M.chainFolded, M.chainOffMap = folded, offMap
    M.routeState = "drawn"

    -- The pass is over: drop whatever it did not take this time (the
    -- whole loop lives in PoolEnd, above, for the same sixty-upvalue
    -- ceiling PoolBegin exists for).
    PoolEnd()

    -- The guide's own shapes -- farm circuits, patrols, search areas --
    -- drawn AFTER the route (their sublevels keep them under it) in the
    -- same pass: one refresh owns both layers, and every early exit that
    -- skips the route still takes them through their own pass above.
    -- During a corpse run the guide is not being walked, so its shapes
    -- come DOWN here instead: the run back to the body is the only thing
    -- the map owes -- farm and patrol overlays come down in corpse mode
    -- too.
    if corpse then
        OverlayRelease()
    else
        OverlayDraw(db, displayID, w, h, boost)
    end
end

-- What a frame is made of, in one status line: every texture region it
-- owns as layer:sublevel, with the NAMED ones kept -- the counts say
-- where the map's own art sits and which slot its icons occupy, which is
-- the one fact the corpse stroke's placement has been guessing at. The
-- list is capped because a map can own hundreds of regions.
local function LayerDump(frame, cap)
    if not (frame and type(frame.GetRegions) == "function") then return "none" end
    local ok, regs = pcall(frame.GetRegions, frame)
    if not (ok and type(regs) == "table") then return "?" end
    local counts, named = {}, {}
    for i = 1, #regs do
        local r = regs[i]
        if r and r.GetDrawLayer then
            local okL, layer, sub = pcall(r.GetDrawLayer, r)
            if okL and layer then
                local k = tostring(layer) .. ":" .. tostring(sub or 0)
                counts[k] = (counts[k] or 0) + 1
                local n = r.GetName and r:GetName()
                if type(n) == "string" and n ~= "" and #named < 6 then
                    named[#named + 1] = n .. "(" .. k .. ")"
                end
            end
        end
    end
    local keys = {}
    for k, v in pairs(counts) do keys[#keys + 1] = k .. "*" .. v end
    table.sort(keys)
    if #keys == 0 then return "0 regions" end
    local out = table.concat(keys, ",")
    if #named > 0 then out = out .. " [" .. table.concat(named, " ") .. "]" end
    return out
end

-- The same question for the FRAMES over the map: children bucketed by
-- frame level, named ones kept. A texture's draw layer answers "under or
-- over the art"; a child frame's LEVEL answers "under or over the other
-- children" -- the pins, the player arrow, our own route frame. Bucketed,
-- so a canvas holding forty pins still prints in one line.
local function KidDump(frame)
    if not (frame and frame.GetChildren) then return "none" end
    local ok, kids = pcall(frame.GetChildren, frame)
    if not (ok and type(kids) == "table") then return "?" end
    local byLvl, lo, hi, named = {}, nil, nil, {}
    for i = 1, #kids do
        local k = kids[i]
        if k then
            local okL, lvl = pcall(k.GetFrameLevel, k)
            if okL and type(lvl) == "number" then
                byLvl[lvl] = (byLvl[lvl] or 0) + 1
                lo = lo and math.min(lo, lvl) or lvl
                hi = hi and math.max(hi, lvl) or lvl
                if #named < 4 and k.GetName then
                    local okN, nm = pcall(k.GetName, k)
                    if okN and type(nm) == "string" and nm ~= "" then
                        named[#named + 1] = nm .. "@" .. lvl
                    end
                end
            end
        end
    end
    if not lo then return #kids .. " (no levels)" end
    local lv = {}
    for lvl in pairs(byLvl) do lv[#lv + 1] = lvl end
    table.sort(lv)
    local s = {}
    for i = 1, math.min(#lv, 6) do s[#s + 1] = lv[i] .. "*" .. byLvl[lv[i]] end
    local out = #kids .. " kids lv" .. lo .. ".." .. hi
        .. " (" .. table.concat(s, ",") .. ")"
    if #named > 0 then out = out .. " [" .. table.concat(named, " ") .. "]" end
    return out
end

-- And the map's own pin registry, when this client keeps one: which pin
-- templates it currently holds and how many of each, plus whatever frame
-- level table it exposes. "QuestPinTemplate*6" in a capture names the
-- exact family the route must slide under.
local function PinDump(wm)
    local out = {}
    if wm and type(wm.GetNumActivePinsByTemplate) == "function" then
        for _, tpl in ipairs({ "QuestPinTemplate", "AreaPOIPinTemplate",
            "ScenarioPinTemplate", "TaskPOIPinTemplate", "PlayerPinTemplate",
            "CorpsePinTemplate", "GraveyardPinTemplate" }) do
            local ok, n = pcall(wm.GetNumActivePinsByTemplate, wm, tpl)
            if ok and type(n) == "number" and n > 0 then
                out[#out + 1] = tpl .. "*" .. n
            end
        end
    end
    if wm and type(wm.pinFrameLevels) == "table" then
        local ks = {}
        for k in pairs(wm.pinFrameLevels) do ks[#ks + 1] = tostring(k) end
        table.sort(ks)
        local s = {}
        for i = 1, math.min(#ks, 6) do
            local v = wm.pinFrameLevels[ks[i]]
            s[#s + 1] = ks[i] .. "=" .. (type(v) == "number" and v or type(v))
        end
        if #s > 0 then out[#out + 1] = "pfl " .. table.concat(s, ",") end
    end
    return table.concat(out, " ")
end

-- Why is nothing drawn? Every stage a pass goes through, in one line, so a
-- blank map can be told apart from a broken projection by reading rather
-- than guessing. /euirxp status prints this while the route is on.
function M.Diagnose()
    local db = DB()
    local parts = {}
    local function say(k, v) parts[#parts + 1] = k .. "=" .. tostring(v) end
    local function xy(a, b)
        if type(a) == "number" and type(b) == "number" then
            return ("%.2f/%.2f"):format(a, b)
        end
        return "nil"
    end
    say("on", not not (db and db.rxpMapRoute))
    local wm = _G.WorldMapFrame
    say("mapFrame", not not wm)
    say("mapShown", not not (wm and wm.IsShown and wm:IsShown()))
    local af = _G.RXPG_ARROW
    say("arrowFrame", not not af)
    say("element", not not (af and af.element))
    local displayID = DisplayMapID()
    say("displayMap", displayID or "?")
    local targetID, x, y, src = CurrentSpot()
    local dead = IsCorpseRun()
    local corpse = false
    if dead then
        local cid, cx, cy = CorpseSpot()
        if cid then
            targetID, x, y, src, corpse = cid, cx, cy, "corpse", true
        end
    end
    say("targetMap", targetID or "?")
    say("targetFrom", src or "?")
    -- One line that tells a blank map caused by the guide going quiet
    -- apart from one where the body has not been found yet -- dead, and
    -- where the run back to it stands.
    say("corpse", corpse and "run to body"
        or (dead and "body not found" or "alive"))
    if targetID and x then say("elementXY", xy(x, y)) end
    -- The element's own field names, once: if the two answers above both
    -- miss, this is what says where the position actually lives.
    if af and af.element and type(af.element) == "table" then
        local ks = {}
        for k in pairs(af.element) do ks[#ks + 1] = tostring(k) end
        table.sort(ks)
        local shown, out = 0, {}
        for _, k in ipairs(ks) do
