local COMPASS = { "N", "NE", "E", "SE", "S", "SW", "W", "NW" }

-- The arrow card's own thresholds: green under 30, yellow to 100, red
-- beyond -- so the tooltip and the arrow agree about what "far" means.
local function DistColor(d)
    if d and d < 30 then return 0.37, 0.88, 0.48 end
    if d and d <= 100 then return 1.00, 0.85, 0.29 end
    return 0.95, 0.32, 0.32
end

-- A world position through Blizzard's own map API -- the measurement
-- RestedXP's own arrow makes too. Both ends of a tooltip distance go
-- through the same map, so they share an axis convention by construction
-- and neither has to trust the orientation of the client's world axes.
local function MapWorldPos(mapID, x, y)
    if not (C_Map and C_Map.GetWorldPosFromMapPos) then return nil end
    if type(mapID) ~= "number" or type(x) ~= "number" or type(y) ~= "number" then return nil end
    local ok, continent, world = pcall(C_Map.GetWorldPosFromMapPos, mapID, { x = x, y = y })
    if not (ok and continent and world) then return nil end
    local wx, wy
    if type(world.GetXY) == "function" then wx, wy = world:GetXY() else wx, wy = world.x, world.y end
    if type(wx) ~= "number" or type(wy) ~= "number" or IsSecret(wx) or IsSecret(wy) then return nil end
    return wx, wy, continent
end

-- The distance between two world positions, or nil when either is missing
-- or the answer is nonsense: only a number that could really be walked is
-- ever handed on to a tooltip.
local function WorldDist(x1, y1, x2, y2)
    if not (x1 and y1 and x2 and y2) then return nil end
    local dx, dy = x2 - x1, y2 - y1
    local d = math.sqrt(dx * dx + dy * dy)
    if d == d and d >= 0 and d < 1000000 then return d end
    return nil
end

-- Rough arrival time. GetUnitSpeed() can answer a protected number on this
-- client and secret values may not be used in arithmetic, so the pace is
-- assumed instead of measured: 7 yd/s on foot, 14 mounted -- the two
-- paces any route estimator would use. The tilde is not
-- decoration, it is true: this is an estimate, not a schedule.
local function ETA(dist)
    if type(dist) ~= "number" or dist <= 0 then return nil end
    local speed = 7
    if type(IsMounted) == "function" then
        local ok, m = pcall(IsMounted)
        if ok and m then speed = 14 end
    end
    local sec = math.floor(dist / speed + 0.5)
    if sec >= 3600 then
        return string.format("~%d:%02d:%02d", math.floor(sec / 3600),
            math.floor((sec % 3600) / 60), sec % 60)
    end
    return string.format("~%d:%02d", math.floor(sec / 60), sec % 60)
end

-- How far, which way, roughly when, on one line. The direction is read
-- from the displayed map itself (x runs east, y runs south) so the
-- compass says where the MARKER sits on screen, north up, instead of
-- guessing at the client's world axes -- and the distance is measured
-- between the two positions the route was drawn from. With no player
-- position on this map -- another continent in view, say -- the whole
-- line stays away rather than showing half an answer.
-- `cum` is the distance along the ROUTE as far as this marker: what the
-- pass already measured from the player to the marker before it, plus this
-- last leg. A marker three steps ahead then reports the whole way to it --
-- distance and arrival time adding up along the chain, which is the walk
-- the player would really make -- instead of each marker restarting from
-- the player towards a point that is not the next one. Without it (no
-- measurement in the pass, or the current target) the marker reports its
-- own straight line, which for the current target is the same number.
local function NavLine(mapID, mx, my, cum)
    if type(mapID) ~= "number" or type(mx) ~= "number" or type(my) ~= "number" then return nil end
    local px, py = PlayerSpot(mapID)
    if not (px and py) then return nil end
    local db = DB()
    local unit = (db and db.rxpMeters) and "m" or "yd"
    local dist = (type(cum) == "number") and cum or nil
    if not dist then
        -- Two calls kept apart on purpose: MapWorldPos answers three
        -- values, and WorldDist wants four separate ones.
        local pwx, pwy = MapWorldPos(mapID, px, py)
        local twx, twy = MapWorldPos(mapID, mx, my)
        dist = WorldDist(pwx, pwy, twx, twy)
    end
    local parts = {}
    if dist then
        -- Meters and yards are the same number in WoW (1 yd = 1 m), so
        -- the unit follows the Arrow page's Meters option and the number
        -- never changes with it.
        if unit == "m" and dist >= 1000 then
            parts[#parts + 1] = string.format("%.1f km", dist / 1000)
        else
            parts[#parts + 1] = string.format("%d %s", math.floor(dist + 0.5), unit)
        end
    end
    local ang = math.atan2(mx - px, py - my)
    local k = math.floor((ang + math.pi / 8) / (math.pi / 4)) % 8
    parts[#parts + 1] = COMPASS[k + 1]
    local eta = dist and ETA(dist)
    if eta then parts[#parts + 1] = "ETA " .. eta end
    local r, g, b = 0.85, 0.85, 0.85
    if dist then r, g, b = DistColor(dist) end
    return table.concat(parts, "  -  "), r, g, b
end

local function QuestLines(e)
    local qid = QuestID(e)
    if not qid or not GameTooltip or type(C_QuestLog) ~= "table" then return end
    local title = QuestTitle(qid)
    if title then GameTooltip:AddLine(title, 1.00, 0.80, 0.20) end
    local level, idx, ready, done = QuestState(qid)
    if level then
        local r, g, b = DifficultyColor(level)
        GameTooltip:AddLine("Level " .. tostring(level), r, g, b)
    end
    -- Four states, in the order a player reads them: can I hand it in,
    -- is it done, is it even in my log, or is it still ahead of me.
    if ready then
        GameTooltip:AddLine("Ready to turn in", 0.37, 0.88, 0.48)
    elseif done then
        GameTooltip:AddLine("Completed", 0.55, 0.85, 0.55)
    elseif idx then
        GameTooltip:AddLine("In the quest log", 0.85, 0.85, 0.85)
    else
        GameTooltip:AddLine("Not in the quest log", 0.70, 0.70, 0.70)
    end
    if type(C_QuestLog.GetQuestObjectives) == "function" then
        local ok, objs = pcall(C_QuestLog.GetQuestObjectives, qid)
        if ok and type(objs) == "table" then
            for _, o in ipairs(objs) do
                if type(o) == "table" and type(o.text) == "string" and o.text ~= "" then
                    local line = o.text
                    if type(o.numRequired) == "number" and o.numRequired > 0 then
                        line = string.format("%d/%d %s",
                            tonumber(o.numFilled) or 0, o.numRequired, line)
                    end
                    GameTooltip:AddLine(line, 0.85, 0.85, 0.85, true)
                end
            end
        end
    end
    -- Last of the quest block: the id, dim, for the player who wants to
    -- look the quest up elsewhere. It trails the objectives on purpose --
    -- it is the one number nobody reads twice.
    GameTooltip:AddLine("Quest ID " .. tostring(qid), 0.62, 0.62, 0.62)
end

-- One switch per group of lines, so a player who reads the map for the
