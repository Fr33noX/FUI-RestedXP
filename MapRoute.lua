    -- line, not a guessing game.
    say("shapes", M.overlayDrawn ~= nil and tostring(M.overlayDrawn) or "-")
    say("why", M.overlayWhy or "-")
    say("sample", M.overlaySample or "-")
    return table.concat(parts, "  ")
end

